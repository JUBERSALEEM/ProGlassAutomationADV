#!/usr/bin/env node
/**
 * The language menu's coverage numbers, built into a static table.
 *
 * Why this script exists: the menu renders one percentage per language.
 * While those numbers were computed in the browser (`coverageOf` over the
 * whole dictionary registry), every visitor downloaded all fifteen
 * dictionaries — ~4.6 MB of the shared root chunk, out of ~5.5 MB — to
 * display fifteen integers. The table is computed here, at build time, from
 * the same sources, and the menu imports the table: a few hundred bytes,
 * always true for the build it ships in. That is the same architecture the
 * translator already keeps: the server loads the dictionaries, the client
 * receives only what it renders.
 *
 * Run via `npm run i18n:keys`, which regenerates `keys.ts` first — the table
 * always counts against the current sentence list.
 */
import { readFileSync, writeFileSync } from "node:fs";

const KEYS = [...readFileSync("src/i18n/dict/keys.ts", "utf8").matchAll(/^ {2}(".*"),$/gm)].map(
  (match) => JSON.parse(match[1]),
);

const LOCALES = [
  "en-US", "ar-AE", "bn-BD", "de-DE", "es-ES", "fr-FR", "hi-IN", "id-ID",
  "ja-JP", "ko-KR", "pt-BR", "ru-RU", "tr-TR", "ur-PK", "zh-CN",
];

/** `"key": "value"` pairs, one per line — the format the fill scripts write. */
function dictionary(locale) {
  const source = readFileSync(`src/i18n/dict/${locale}.ts`, "utf8");
  const entries = new Map();
  for (const match of source.matchAll(/^\s*"((?:[^"\\]|\\.)*)":\s*"((?:[^"\\]|\\.)*)",?$/gm)) {
    entries.set(JSON.parse(`"${match[1]}"`), JSON.parse(`"${match[2]}"`));
  }
  return entries;
}

const table = {};
for (const locale of LOCALES) {
  const isSource = locale === "en-US"; // the key is the English sentence
  const entries = isSource ? new Map() : dictionary(locale);
  const sentences = isSource
    ? KEYS.length
    : KEYS.filter((key) => {
        const value = entries.get(key);
        return typeof value === "string" && value.trim() !== "";
      }).length;
  let appVocabulary = 0;
  try {
    appVocabulary = Object.keys(JSON.parse(readFileSync(`src/i18n/app-strings/${locale}.json`, "utf8"))).length;
  } catch {
    // The app-strings file is generated by i18n:import-app; in a tree that has
    // not run it, zero is the truthful count rather than a failure.
  }
  const total = KEYS.length;
  table[locale] = {
    sentences,
    total,
    percent: total === 0 ? 100 : Math.round((sentences / total) * 100),
    complete: sentences === total && total > 0,
    appVocabulary,
  };
}

writeFileSync("src/i18n/coverage-table.json", JSON.stringify(table, null, 2) + "\n");

const summary = LOCALES.map((locale) => `${locale} ${table[locale].percent}%`).join(" · ");
console.log(
  `coverage table: ${LOCALES.length} languages × ${KEYS.length} sentences — ${summary}`,
);
console.log("  written to src/i18n/coverage-table.json");
