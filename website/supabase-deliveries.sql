CREATE OR REPLACE FUNCTION public.trg_delivery_entries_set_timestamps()
RETURNS TRIGGER AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.created_at = COALESCE(NEW.created_at, NOW());
    NEW.updated_at = NOW();
  ELSIF TG_OP = 'UPDATE' THEN
    NEW.updated_at = NOW();
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_delivery_entries_timestamps ON public.delivery_entries;
CREATE TRIGGER trg_delivery_entries_timestamps
BEFORE INSERT OR UPDATE ON public.delivery_entries
FOR EACH ROW
EXECUTE FUNCTION public.trg_delivery_entries_set_timestamps();

-- ---------------------------------------------------------------------
-- 3. OVER-DELIVERY: REPORTED, NOT REFUSED (with an opt-in strict guard)
-- ---------------------------------------------------------------------
-- The desktop application's delivery-note validator refuses a movement that
-- would exceed what was ordered, and that is the right behaviour at the point
-- of entry: the operator is standing in front of the note and can fix it.
--
-- This database is a second point of entry — imports, corrections, bulk
-- backfills — and refusing a row there loses it silently behind a failed
-- sync. So the default is the opposite: accept the row, compute the excess in
-- `pi_delivery_balance` (rework exemptions included), and let the tracker
-- raise it as an over-delivery on the PI. A visible anomaly beats an invisible
-- one.
--
-- A project that wants the refusal anyway can enable the guard below. It is
-- written, not enabled: turning it on for a dataset that is mid-correction
-- would reject the correction along with the error.
--
--   CREATE TRIGGER trg_delivery_entries_strict_balance
--   BEFORE INSERT OR UPDATE ON public.delivery_entries
--   FOR EACH ROW EXECUTE FUNCTION public.assert_delivery_within_balance();

CREATE OR REPLACE FUNCTION public.assert_delivery_within_balance()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_ordered   numeric := 0;
  v_delivered numeric := 0;
  v_rework    numeric := 0;
BEGIN
  -- Voided and drafting notes never count, so they are never refused.
  IF NEW.is_void OR lower(BTRIM(COALESCE(NEW.status, ''))) IN ('draft','dispatching','preparing','cancelled','canceled','void','voided','reversed') THEN
    RETURN NEW;
  END IF;

  SELECT COALESCE(SUM(COALESCE(NULLIF(BTRIM(qty), ''), '0')::numeric), 0)
    INTO v_ordered
  FROM public.records
  WHERE is_active IS NOT FALSE AND pi_number = NEW.pi_number;

  SELECT
    COALESCE(SUM(CASE WHEN lower(BTRIM(delivery_type)) = 'return'
                      THEN -ABS(delivered_qty) ELSE delivered_qty END), 0),
    COALESCE(SUM(CASE WHEN lower(BTRIM(delivery_type)) IN ('rework','replacement','remake')
                      THEN delivered_qty ELSE 0 END), 0)
    INTO v_delivered, v_rework
  FROM public.delivery_entries
  WHERE pi_number = NEW.pi_number
    AND is_void = false
    AND lower(BTRIM(status)) NOT IN ('draft','dispatching','preparing','cancelled','canceled','void','voided','reversed')
    AND id <> COALESCE(NEW.id, -1);

  IF v_ordered > 0 AND (v_delivered + NEW.delivered_qty) - v_ordered > v_rework THEN
    RAISE EXCEPTION
      'Delivery of % pcs on % would take PI % to % pcs against % ordered.',
      NEW.delivered_qty, NEW.pi_number, NEW.pi_number,
      (v_delivered + NEW.delivered_qty), v_ordered
      USING HINT = 'Void the note, record it as Rework/Replacement, or correct the ordered quantity first.';
  END IF;

  RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------
-- 4. THE BALANCE VIEW — THE ONE PLACE THE MATHS LIVES
-- ---------------------------------------------------------------------
-- One row per PI: what the ledger says has moved. The obligation (what was
-- ordered) comes from public.records and is joined by PI number, because the
-- two tables are owned by different writers: records by Excel Sync, entries by
-- dispatch. Keeping them separate and joining in the view is what allows a
-- retried sync to rewrite the obligation without touching the movements.

CREATE OR REPLACE VIEW public.pi_delivery_balance AS
WITH movement_totals AS (
  SELECT
    de.pi_number,
    COUNT(*) FILTER (WHERE de.is_void = false AND lower(BTRIM(de.status)) NOT IN ('draft','dispatching','preparing','cancelled','canceled','void','voided','reversed')) AS counted_movements,
    COUNT(*)                                                                                                    AS total_movements,
    COALESCE(SUM(
      CASE
        WHEN de.is_void OR lower(BTRIM(de.status)) IN ('draft','dispatching','preparing','cancelled','canceled','void','voided','reversed') THEN 0
        WHEN lower(BTRIM(de.delivery_type)) = 'return' THEN -ABS(de.delivered_qty)
        ELSE de.delivered_qty
      END), 0) AS delivered_qty,
    COALESCE(SUM(
      CASE
        WHEN de.is_void OR lower(BTRIM(de.status)) IN ('draft','dispatching','preparing','cancelled','canceled','void','voided','reversed') THEN 0
        WHEN lower(BTRIM(de.delivery_type)) = 'return' THEN -ABS(de.delivered_sqm)
        ELSE de.delivered_sqm
      END), 0) AS delivered_sqm,
    COALESCE(SUM(
      CASE
        WHEN de.is_void OR lower(BTRIM(de.status)) IN ('draft','dispatching','preparing','cancelled','canceled','void','voided','reversed') THEN 0
        WHEN lower(BTRIM(de.delivery_type)) IN ('rework','replacement','remake') THEN de.delivered_qty
        ELSE 0
      END), 0) AS rework_qty,
    MAX(de.delivery_date) FILTER (
      WHERE de.is_void = false AND lower(BTRIM(de.status)) NOT IN ('draft','dispatching','preparing','cancelled','canceled','void','voided','reversed')
    ) AS last_delivery_date
  FROM public.delivery_entries de
  GROUP BY de.pi_number
),
obligation AS (
  SELECT
    r.pi_number,
    SUM(COALESCE(NULLIF(BTRIM(r.qty), ''), '0')::numeric) AS ordered_qty,
    SUM(COALESCE(NULLIF(BTRIM(r.sqm), ''), '0')::numeric) AS ordered_sqm,
    COUNT(*) AS record_row_count
  FROM public.records r
  WHERE r.is_active IS NOT FALSE
    AND r.pi_number IS NOT NULL
    AND BTRIM(r.pi_number) <> ''
  GROUP BY r.pi_number
)
SELECT
  COALESCE(o.pi_number, m.pi_number)                       AS pi_number,
  COALESCE(o.ordered_qty, 0)                               AS ordered_qty,
  COALESCE(o.ordered_sqm, 0)                               AS ordered_sqm,
  COALESCE(o.record_row_count, 0)                          AS record_row_count,
  COALESCE(m.delivered_qty, 0)                             AS delivered_qty,
  COALESCE(m.delivered_sqm, 0)                             AS delivered_sqm,
  COALESCE(m.rework_qty, 0)                                AS rework_qty,
  GREATEST(COALESCE(o.ordered_qty, 0) - COALESCE(m.delivered_qty, 0), 0) AS balance_qty,
  GREATEST(COALESCE(o.ordered_sqm, 0) - COALESCE(m.delivered_sqm, 0), 0) AS balance_sqm,
  COALESCE(m.counted_movements, 0)                         AS delivery_count,
  COALESCE(m.total_movements, 0)                           AS total_movement_count,
  m.last_delivery_date,
  -- The lifecycle, derived here so no screen has to invent it.
  CASE
    WHEN COALESCE(m.delivered_qty, 0) <= 0 THEN 'awaiting_dispatch'
    WHEN COALESCE(o.ordered_qty, 0) <= 0 THEN 'over_delivered'
    WHEN COALESCE(m.delivered_qty, 0) > COALESCE(o.ordered_qty, 0)
         AND (COALESCE(m.delivered_qty, 0) - COALESCE(o.ordered_qty, 0)) > COALESCE(m.rework_qty, 0)
      THEN 'over_delivered'
    WHEN COALESCE(m.delivered_qty, 0) >= COALESCE(o.ordered_qty, 0) THEN 'complete'
    ELSE 'partial'
  END                                                      AS delivery_status
FROM obligation o
FULL OUTER JOIN movement_totals m ON m.pi_number = o.pi_number;

-- Views inherit the privileges of their owner; grant read to the dashboard
-- roles explicitly. Row Level Security on the underlying tables still applies
-- to SECURITY INVOKER access paths.
ALTER VIEW public.pi_delivery_balance SET (security_invoker = true);
GRANT SELECT ON public.pi_delivery_balance TO anon, authenticated, service_role;

-- ---------------------------------------------------------------------
-- 5. DASHBOARD AGGREGATION RPC (OPTIONAL BUT RECOMMENDED)
-- ---------------------------------------------------------------------
-- The tracker computes its figures in TypeScript today, over a bounded read
-- (10 000 rows) that is reported in the UI when it is reached. For datasets
-- past that ceiling, this function computes the same numbers inside
-- PostgreSQL, so the page can read one row of JSON instead of ten thousand
-- rows of ledger. The page does not call it yet; it is provided so scaling
-- past the ceiling is a deployment change rather than a rewrite.
--
-- The WHERE clauses below are the same ones `filterDeliveryRows` applies in
-- TypeScript. If one changes, change the other — they are two implementations
-- of one specification.

CREATE OR REPLACE FUNCTION public.get_deliveries_dashboard_aggregates(
  p_search          text    DEFAULT NULL,
  p_company         text    DEFAULT NULL,
  p_salesman        text    DEFAULT NULL,
  p_prepared_by     text    DEFAULT NULL,
  p_type_of_work    text    DEFAULT NULL,
  p_delivery_status text    DEFAULT NULL,
  p_balance_only    boolean DEFAULT false,
  p_date_from       date    DEFAULT NULL,
  p_date_to         date    DEFAULT NULL,
  p_confirmed_only  boolean DEFAULT true
)
RETURNS json
LANGUAGE plpgsql
STABLE
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_summary  json;
  v_status   json;
  v_company  json;
  v_salesman json;
  v_work     json;
  v_search   text;
BEGIN
  v_search := CASE
    WHEN p_search IS NULL OR BTRIM(p_search) = '' THEN NULL
    ELSE '%' || BTRIM(p_search) || '%'
  END;

  WITH scope AS (
    SELECT
      b.*,
      COALESCE(r.company, '')      AS company,
      COALESCE(r.salesman, '')     AS salesman,
      COALESCE(r.prepared_by, '')  AS prepared_by,
      COALESCE(r.type_of_work, '') AS type_of_work,
      COALESCE(r.date::text, '')   AS order_date,
      COALESCE(r.status, '')       AS record_status
    FROM public.pi_delivery_balance b
    LEFT JOIN LATERAL (
      SELECT r.*
      FROM public.records r
      WHERE r.is_active IS NOT FALSE
        AND r.pi_number = b.pi_number
      ORDER BY COALESCE(r.updated_at, r.created_at) DESC NULLS LAST, r.date DESC NULLS LAST
      LIMIT 1
    ) r ON true
  ),
  filtered AS (
    SELECT *
    FROM scope s
    WHERE (p_company IS NULL OR p_company = '' OR s.company = p_company)
      AND (p_salesman IS NULL OR p_salesman = '' OR s.salesman = p_salesman)
      AND (p_prepared_by IS NULL OR p_prepared_by = '' OR s.prepared_by = p_prepared_by)
      AND (p_type_of_work IS NULL OR p_type_of_work = '' OR s.type_of_work = p_type_of_work)
      AND (p_delivery_status IS NULL OR p_delivery_status = '' OR s.delivery_status = p_delivery_status)
      AND (NOT COALESCE(p_balance_only, false) OR s.balance_qty > 0)
      -- NULLIF, not ''::date: an unparseable order date must drop out of a
      -- date-filtered result, not raise inside the query.
      AND (p_date_from IS NULL OR NULLIF(s.order_date, '')::date >= p_date_from)
      AND (p_date_to   IS NULL OR NULLIF(s.order_date, '')::date <= p_date_to)
      AND (
        v_search IS NULL
        OR s.pi_number ILIKE v_search
        OR s.company ILIKE v_search
      )
      -- The eligibility rule: a confirmed PI, or a PI that already moved.
      AND (NOT COALESCE(p_confirmed_only, true) OR s.delivery_count > 0 OR s.record_status = 'Confirmed')
  )
  SELECT json_build_object(
    'totalPis',            COUNT(*),
    'totalMovements',      COALESCE(SUM(delivery_count), 0),
    'orderedQty',          COALESCE(SUM(ordered_qty), 0),
    'orderedSqm',          COALESCE(SUM(ordered_sqm), 0),
    'deliveredQty',        COALESCE(SUM(delivered_qty), 0),
    'deliveredSqm',        COALESCE(SUM(delivered_sqm), 0),
    'balanceQty',          COALESCE(SUM(balance_qty), 0),
    'balanceSqm',          COALESCE(SUM(balance_sqm), 0),
    'awaitingDispatchPIs', COUNT(*) FILTER (WHERE delivery_status = 'awaiting_dispatch'),
    'partiallyDeliveredPIs', COUNT(*) FILTER (WHERE delivery_status = 'partial'),
    'fullyDeliveredPIs',   COUNT(*) FILTER (WHERE delivery_status IN ('complete','over_delivered')),
    'overDeliveredPIs',    COUNT(*) FILTER (WHERE delivery_status = 'over_delivered')
  ) INTO v_summary
  FROM filtered;

  SELECT COALESCE(json_agg(row_to_json(t)), '[]'::json) INTO v_status FROM (
    SELECT delivery_status AS name, COUNT(*) AS count,
           SUM(ordered_qty) AS ordered_qty, SUM(delivered_qty) AS delivered_qty,
           SUM(balance_qty) AS balance_qty, SUM(balance_sqm) AS balance_sqm
    FROM filtered GROUP BY delivery_status ORDER BY count DESC
  ) t;

  SELECT COALESCE(json_agg(row_to_json(t)), '[]'::json) INTO v_company FROM (
    SELECT company AS name, COUNT(*) AS count, SUM(balance_sqm) AS balance_sqm
    FROM filtered GROUP BY company ORDER BY COUNT(*) DESC LIMIT 20
  ) t;

  SELECT COALESCE(json_agg(row_to_json(t)), '[]'::json) INTO v_salesman FROM (
    SELECT salesman AS name, COUNT(*) AS count, SUM(balance_sqm) AS balance_sqm
    FROM filtered GROUP BY salesman ORDER BY COUNT(*) DESC LIMIT 20
  ) t;

  SELECT COALESCE(json_agg(row_to_json(t)), '[]'::json) INTO v_work FROM (
    SELECT type_of_work AS name, COUNT(*) AS count, SUM(balance_sqm) AS balance_sqm
    FROM filtered GROUP BY type_of_work ORDER BY COUNT(*) DESC LIMIT 20
  ) t;

  RETURN json_build_object(
    'summary', v_summary,
    'breakdowns', json_build_object(
      'lifecycle', v_status,
      'company',   v_company,
      'salesman',  v_salesman,
      'typeOfWork', v_work
    )
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.get_deliveries_dashboard_aggregates
  TO anon, authenticated, service_role;

