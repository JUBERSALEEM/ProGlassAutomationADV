-- =====================================================================
-- APPENDIX — what a well-formed ledger looks like for one PI
-- =====================================================================
-- PI-2026-1004 ordered 72 pieces / 63.40 m², delivered in three movements
-- and one rejection:
--
--   INSERT INTO public.delivery_entries
--     (pi_number, delivery_note_ref, sequence, delivery_date, delivered_qty, delivered_sqm,
--      delivery_type, status, driver_name, vehicle_number, receiver_name)
--   VALUES
--     ('PI-2026-1004', 'DN-2026-004-01', 1, DATE '2026-10-06', 30, 26.40, 'Original', 'Signed',
--      'Rashid Ali', 'DXB-C-4471', 'Site engineer'),
--     ('PI-2026-1004', 'DN-2026-004-02', 2, DATE '2026-10-11', 24, 21.10, 'Original', 'Received',
--      'Rashid Ali', 'DXB-C-4471', 'Site engineer'),
--     ('PI-2026-1004', 'DN-2026-004-03', 3, DATE '2026-10-18',  2,  1.80, 'Rework',   'Dispatched',
--      'Rashid Ali', 'DXB-C-4471', NULL),
--     ('PI-2026-1004', 'DN-2026-004-04', 4, DATE '2026-10-22',  1,  0.90, 'Return',   'Received',
--      'Rashid Ali', 'DXB-C-4471', 'Site engineer');
--
--   SELECT pi_number, ordered_qty, delivered_qty, balance_qty, delivery_status
--   FROM public.pi_delivery_balance WHERE pi_number = 'PI-2026-1004';
--
--   → 55 delivered (30 + 24 + 2 − 1), 17 owed against 72 ordered, status 'partial'.
-- =====================================================================
