-- =====================================================================
-- PROGLASS AUTOMATION — DELIVERIES TRACKER / DELIVERY LEDGER
-- Project: afpbdyamedpanwijxghk  (same project as supabase-dashboard.sql)
-- Tables: public.delivery_entries  ·  View: public.pi_delivery_balance
-- =====================================================================
--
-- The Deliveries Tracker reads `public.records` for the obligation (which
-- confirmed PIs exist and how much was ordered) and this table for the
-- movements (what actually left the building, when, on which note).
--
-- Run this once in the Supabase SQL editor, AFTER supabase-dashboard.sql:
-- https://supabase.com/dashboard/project/afpbdyamedpanwijxghk/sql
--
-- Nothing here touches public.records. The tracker works without this file —
-- it simply shows every confirmed PI as awaiting dispatch, and says so — but
-- with it, part deliveries, balances and the movement history become real.
--
-- ---------------------------------------------------------------------
-- WHY A LEDGER AND NOT A STATUS COLUMN
-- ---------------------------------------------------------------------
-- A job goes out over several movements: four pieces on Tuesday's vehicle,
-- the balance on Friday, a replacement pane the week after. If the delivery
-- state lived in a single "delivered qty" column on the PI row, every part
-- load would be an UPDATE and the history — who signed for what, on which
-- note — would be gone. So each movement is a ROW, and the balance is a
-- query over the rows. The rules that turn rows into a balance are:
--
--   · is_void = true            → never counts (soft-close, audited)
--   · status Draft/Dispatching  → does not count (it has not left yet)
--     (the full exclusion list is: draft, dispatching, preparing, cancelled,
--      canceled, void, voided, reversed — and it is mirrored exactly in
--      src/lib/delivery-ledger.ts; a status added to one belongs in the other)
--   · delivery_type Return      → subtracts (goods came back)
--   · delivery_type Rework /
--     Replacement               → adds, and explains an over-delivery
--
-- These rules are implemented once, in the `pi_delivery_balance` view below,
-- and mirrored once, in `website/src/lib/delivery-ledger.ts`. Two owners
-- would be one too many: the whole point of this page is that there is a
-- single answer to "how much is still owed".
--
-- ---------------------------------------------------------------------

-- ---------------------------------------------------------------------
-- 1. THE LEDGER TABLE
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.delivery_entries (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  -- Which proforma this movement belongs to. Matches public.records.pi_number.
  pi_number         text        NOT NULL,

  -- User-facing note reference, e.g. "DN-2026-001-02". Unique when present so
  -- a retried sync cannot double-count a movement; nullable because a manual
  -- entry may legitimately arrive before the note is numbered.
  delivery_note_ref text,

  -- Sequence within the PI (1, 2, 3 …). Nullable and informational: the
  -- balance never depends on it, only the ledger's display order does.
  sequence          integer,

  -- When the movement happened, and at what time of day (HH:mm).
  delivery_date     date        NOT NULL DEFAULT CURRENT_DATE,
  delivery_time     text,

  -- Quantities. Both units are stored because glass is ordered in pieces and
  -- invoiced in m², and one of them is always the figure the customer asks for.
  delivered_qty     numeric(14, 3) NOT NULL DEFAULT 0 CHECK (delivered_qty >= 0),
  delivered_sqm     numeric(14, 3) NOT NULL DEFAULT 0 CHECK (delivered_sqm >= 0),

  -- Original | Rework | Replacement | Return | Dummy. Free text on purpose:
  -- the desktop application already has four values and may add a fifth
  -- without a migration, and an unrecognized value must degrade to "counts
  -- like a normal dispatch" rather than be rejected at 19:00 on a Friday.
  delivery_type     text        NOT NULL DEFAULT 'Original',

  -- Draft | Dispatching | Dispatched | Delivered | Signed | Received.
  -- A note with a drafting status is recorded but excluded from the balance.
  status            text        NOT NULL DEFAULT 'Dispatched',

  driver_name       text,
  vehicle_number    text,
  receiver_name     text,
  notes             text,

  -- Soft-close. A voided movement stays for audit and is excluded from every
  -- figure. Rows are never deleted: the ledger is a record of what happened,
  -- including what was cancelled.
  is_void           boolean     NOT NULL DEFAULT false,
  voided_at         timestamptz,
  voided_by         text,
  void_reason       text,

  -- Which workbook/import the row came from, mirroring public.records so the
  -- tracker's workbook scoping applies to movements as well as obligations.
  source_file       text,

  created_at        timestamptz NOT NULL DEFAULT NOW(),
  updated_at        timestamptz NOT NULL DEFAULT NOW()
);

-- One note reference cannot appear twice — catches a replayed sync exactly
-- once, and only when the reference is present.
CREATE UNIQUE INDEX IF NOT EXISTS idx_delivery_entries_note_ref
  ON public.delivery_entries (delivery_note_ref)
  WHERE delivery_note_ref IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_delivery_entries_pi
  ON public.delivery_entries (pi_number);

CREATE INDEX IF NOT EXISTS idx_delivery_entries_pi_date
  ON public.delivery_entries (pi_number, delivery_date);

CREATE INDEX IF NOT EXISTS idx_delivery_entries_date
  ON public.delivery_entries (delivery_date DESC);

CREATE INDEX IF NOT EXISTS idx_delivery_entries_active
  ON public.delivery_entries (pi_number, delivery_date)
  WHERE is_void = false;

CREATE INDEX IF NOT EXISTS idx_delivery_entries_source
  ON public.delivery_entries (source_file);

