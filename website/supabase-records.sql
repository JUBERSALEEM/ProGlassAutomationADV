-- Timestamp trigger — body reproduced verbatim from
-- supabase-dashboard.sql §"trg_records_set_timestamps" so a fresh build
-- behaves identically; that file's CREATE OR REPLACE overwrites it with
-- itself when run after this one.
CREATE OR REPLACE FUNCTION public.trg_records_set_timestamps()
RETURNS TRIGGER AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.created_at = COALESCE(NEW.created_at, NOW());
    NEW.updated_at = COALESCE(NEW.updated_at, NOW());
    NEW.is_active = COALESCE(NEW.is_active, true);
  ELSIF TG_OP = 'UPDATE' THEN
    NEW.updated_at = NOW();
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_records_timestamps ON public.records;
CREATE TRIGGER trg_records_timestamps
  BEFORE INSERT OR UPDATE ON public.records
  FOR EACH ROW EXECUTE FUNCTION public.trg_records_set_timestamps();

