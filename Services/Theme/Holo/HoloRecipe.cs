// MODULE: Holographic / Iridescent — the recipe
//
// ── WHAT MAKES FOIL DIFFERENT FROM A RAINBOW ─────────────────────────
//
// The obvious implementation is a linear-gradient through six evenly
// spaced hues, and it is the single most reliable way to fake this
// family. The design research is unanimous on why:
//
//   "A holographic gradient with evenly distributed colours reads as a
//    kids cartoon, not as foil. The non-uniform banding is what makes
//    it work."  [gradients.design]
//   "Treating it as a uniform rainbow" is listed as common mistake #1.
//
// WHY the banding is non-uniform: real foil works by DIFFRACTION. The
// surface is a grating — fine parallel grooves — and each groove sends
// a different wavelength to your eye from a different angle. The
// rainbow is therefore not painted on; it is the ORDER IN WHICH
// wavelengths separate as you tilt or travel across the surface.
//
// That gives this recipe its central rule: the spectrum is generated by
// a GRATING MODEL, not by walking the hue circle at a constant rate.
// Stop spacing is warped by the diffraction order, so bands differ in
// width. That single decision is the difference between foil and a
// rainbow, and it is why HoloSpectrum does not expose a plain
// "hueStart/hueEnd" pair.
//
// ── AND IT MUST BE MUTED, NOT ELECTRIC ────────────────────────────────
//
//   "Real holographic foil has muted, slightly desaturated colours.
//    Pure saturation reads as children's television."  [gradients.design]
//   "Over-saturating ... reads as a kids cartoon."  [gradients.design]
//
// So every spectral colour is pulled toward its own neutral by a chroma
// ceiling. Saturated primaries are available as INPUTS and are
// deliberately not what comes out.
//
// ── THE ARCHITECTURAL RULE: THE FOIL NEVER GOES UNDER TEXT ───────────
//
// This is the finding that shapes the whole engine, and it is not a
// stylistic preference:
//
//   "Text on top of holographic loses contrast as the colours shift.
//    Test your typography at the brightest and darkest regions; add a
//    semi-transparent overlay if contrast fails."  [gradients.design]
//   "Iridescent foils can wreck icon contrast — use mix-blend-mode or a
//    solid icon chip so glyphs stay legible on every hue."
//                                              [codefronts]
//
// So this family publishes TWO SEPARATE COLOUR SETS and never mixes
// them: an opaque matte GROUND that text is allowed to sit on, and a
// spectral RIM that is decoration only. A control cannot ask for "the
// fill" and accidentally get foil under its own label, because there is
// no single fill to ask for. See HoloStack.HasFoilUnderText, which is a
// constant false for the same reason SwissStack.HasShadow is.
//
// The one place foil DOES go under a glyph is HoloChip, which is the
// signature control of this family — and even there the recipe measures
// the ink against EVERY band of the spectrum and darkens until it
// clears the floor, rather than hoping.
// ═══════════════════════════════════════════════════════════════════════

