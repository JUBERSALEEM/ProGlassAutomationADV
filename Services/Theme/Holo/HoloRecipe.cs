    /// <summary>
    /// One spectral band, with the two numbers that produced it kept
    /// alongside so the recipe can be explained rather than merely
    /// tuned.
    /// </summary>
    public sealed class HoloBand
    {
        internal HoloBand(double offset, double hue, double chroma, Color color)
        {
            Offset = offset;
            Hue = hue;
            Chroma = chroma;
            Color = color;
        }

        /// <summary>
        /// Position along the grating axis, 0..1. NOT evenly spaced —
        /// that is the entire point of the class.
        /// </summary>
        public double Offset { get; }

        /// <summary>Resolved hue, degrees 0..360.</summary>
        public double Hue { get; }

        /// <summary>
        /// Resolved saturation, 0..1, AFTER the chroma ceiling was
        /// applied. Always at or below HoloProfile.ChromaCeiling.
        /// </summary>
        public double Chroma { get; }

        /// <summary>The band colour, already desaturated.</summary>
        public Color Color { get; }
    }

    /// <summary>
    /// The grating. Builds the spectrum, and is the only thing in the
    /// engine permitted to.
    /// </summary>
    public sealed class HoloSpectrum
    {
        private readonly IReadOnlyList<HoloBand> _bands;

        private HoloSpectrum(IReadOnlyList<HoloBand> bands)
        {
            _bands = bands;
        }

        public IReadOnlyList<HoloBand> Bands => _bands;

        public int Count => _bands.Count;

        /// <summary>
        /// The spectral band nearest a position along the grating axis.
        /// Returns the terminal band rather than throwing, because a
        /// brush offset of exactly 1.0 is a legitimate value and a
        /// gradient that threw there would take the render down with it.
        /// </summary>
        public HoloBand At(double offset)
        {
            if (_bands.Count == 0) throw new InvalidOperationException(
                "A holographic spectrum must have at least one band.");

            double t = Math.Clamp(offset, 0.0, 1.0);
            int index = (int)Math.Round(t * (_bands.Count - 1));
            return _bands[Math.Clamp(index, 0, _bands.Count - 1)];
        }

        /// <summary>
        /// Builds the spectrum.
        /// <para>
        /// <para>
        /// The band WIDTHS come from a diffraction widening — see
        /// <see cref="W"/>. The band BRIGHTNESS is held at a single
        /// target luminance, and that second decision is the one that
        /// makes this family usable rather than merely pretty.
        /// </para>
        /// <para>
        /// Why luminance and not HSL lightness: at a constant HSL
        /// lightness a spectrum's WCAG relative luminance ranges
        /// ENORMOUSLY. Yellow-green lands near 0.6 and deep blue near
        /// 0.06 — a tenfold spread from one "lightness" setting. That
        /// is what makes a single ink impossible to keep legible across
        /// a whole gradient, and it is precisely how this family gets
        /// shipped broken: someone tries a handful of inks against a
        /// handful of bands, picks the one that works on the blue, and
        /// the glyph vanishes on the yellow.
        /// </para>
        /// <para>
        /// Real foil does not have this problem, because at any given
        /// observation angle a thin metal film returns roughly the same
        /// amount of light regardless of wavelength. So the bands are
        /// solved to a common luminance and the ink is guaranteed ONCE,
        /// for the whole spectrum, rather than per band.
        /// </para>
        /// </para>
        /// </summary>
        public static HoloSpectrum Build(
            int stops, double startHue, double turns,
            double chromaCeiling, double targetLuminance)
        {
            if (stops < 2) stops = 2;

            double ceiling = Math.Clamp(chromaCeiling, 0.0, 1.0);
            var bands = new List<HoloBand>(stops);

            for (int i = 0; i < stops; i++)
            {
                double t = i / (double)(stops - 1);

                // ── THE GRATING ──
                // Walking hue linearly is the cartoon. Widening the
                // bands along the axis is the foil. Normalised so the
                // warp redistributes band WIDTHS without changing how
                // much spectrum is covered.
                double w = W(i, stops);
                double hue = WrapHue(startHue + w * turns * 360.0);

                // Per-band chroma variation. Constant chroma across a
                // whole spectrum is the second most common tell: real
                // foil's bands differ in VIVACITY as well as in hue,
                // because a band at a grazing angle returns less light.
                double chroma = ceiling * (0.72 + 0.28 * Math.Sin(t * Math.PI));

                bands.Add(new HoloBand(
                    t, hue, chroma,
                    // SOLVED, not assumed. See SolvedForLuminance.
                    SolvedForLuminance(hue, chroma, targetLuminance)));
            }

            return new HoloSpectrum(bands);
        }

        /// <summary>
        /// The HSL lightness at which <paramref name="hue"/> and
        /// <paramref name="chroma"/> land on
        /// <paramref name="targetLuminance"/>.
        /// <para>
        /// Bisection rather than closed form, because there is no closed
        /// form worth having: WCAG luminance is a gamma-decoded weighted
        /// sum, and inverting it against a piecewise HSL ramp would be
        /// a lot of algebra for no benefit.
        /// </para>
        /// <para>
        /// Sixteen iterations converge far below the thing that actually
        /// limits this: the result is an 8-bit RGB colour, so the
        /// achievable luminances are a discrete lattice roughly 0.003
        /// apart in the mid-tones. Measured, the solved bands land
        /// within 0.003 of the target — and that residue is quantisation,
        /// not solver error. It is harmless here because the margin is
        /// about two full contrast points (6.2:1 against a 4.5:1 floor),
        /// but it is why the tests assert 0.005 rather than something
        /// the solver could actually deliver.
        /// </para>
        /// </summary>
        internal static Color SolvedForLuminance(
            double hue, double chroma, double targetLuminance)
        {
            double target = Math.Clamp(targetLuminance, 0.0, 1.0);
            double lo = 0.0;
            double hi = 1.0;

            for (int i = 0; i < 16; i++)
            {
                double mid = (lo + hi) * 0.5;
                double l = HoloPalette.Luminance(FromHsl(hue, chroma, mid));
                if (l < target) lo = mid; else hi = mid;
            }

            return FromHsl(hue, chroma, (lo + hi) * 0.5);
        }

        /// <summary>
        /// The warped position of stop <paramref name="i"/>, normalised so
        /// the sum of consecutive steps is exactly 1.
        /// <para>
        /// Uses a linear widening: the step from stop i to i+1 is
        /// proportional to (1 + k·(2i+1)/2(n-1)), which is why the
        /// numerator carries a quadratic term. Dividing by the
        /// closed-form total — exactly (n-1)(1 + k/2) — is what makes
        /// the warp redistribute band WIDTHS while leaving the total
        /// hue sweep untouched. Without that division the warp would
        /// also change how much spectrum is covered, and every surface
        /// would drift to a different colour.
        /// </para>
        /// <para>
        /// The widening factor is 1.6, giving the widest band about 2.4x
        /// the narrowest. That number is deliberate, and the first
        /// version of this function got it badly wrong: an
        /// inverse-square weighting (w proportional to 1/(1+3t)²) put
        /// 77% of the entire axis into the FIRST band and smeared the
        /// remaining twelve into a 153-degree-to-1.6-degree staircase.
        /// It is non-uniform, which sounds correct, and it looks nothing
        /// like foil — it looks like one rainbow step followed by a
        /// gradient. Foil banding is uneven, not broken.
        /// </para>
        /// </summary>
        internal static double W(int i, int stops)
        {
            int n = stops - 1;
            if (n <= 0) return 0.0;

            return (i + BandWidening * i * i / (2.0 * n))
                 / (n * (1.0 + BandWidening / 2.0));
        }

        /// <summary>
        /// How much wider the last band is than the first, as a multiple.
        /// See <see cref="W"/> for why this is 1.6.
        /// </summary>
        internal const double BandWidening = 1.6;


        private static double WrapHue(double h)
        {
            h %= 360.0;
            return h < 0 ? h + 360.0 : h;
        }

        /// <summary>
        /// HSL to RGB, with the intermediate done in double so a band
        /// never lands on a muddy in-between the way integer HSB does.
        /// </summary>
        internal static Color FromHsl(double h, double s, double l)
        {
            double c = (1.0 - Math.Abs(2.0 * l - 1.0)) * Math.Clamp(s, 0, 1);
            double hp = WrapHue(h) / 60.0;
            double x = c * (1.0 - Math.Abs(hp % 2.0 - 1.0));

            double r, g, b;
            if (hp < 1) { r = c; g = x; b = 0; }
            else if (hp < 2) { r = x; g = c; b = 0; }
            else if (hp < 3) { r = 0; g = c; b = x; }
            else if (hp < 4) { r = 0; g = x; b = c; }
            else if (hp < 5) { r = x; g = 0; b = c; }
            else { r = c; g = 0; b = x; }

            double m = l - c / 2.0;
            return Color.FromRgb(
                Clamp255(r + m), Clamp255(g + m), Clamp255(b + m));
        }

        private static byte Clamp255(double v) =>
            (byte)Math.Round(Math.Clamp(v, 0.0, 1.0) * 255.0);
    }

    /// <summary>Timing and geometry for the foil's movement.</summary>
    public sealed class HoloMotion
    {
        public HoloMotion(
            double driftPeriod, double sweepPeriod,
            double rimAngle, double rimOpacity,
            double sheenOpacity, double sheenWidth)
        {
            DriftPeriod = driftPeriod;
            SweepPeriod = sweepPeriod;
            RimAngle = rimAngle;
            RimOpacity = rimOpacity;
            SheenOpacity = sheenOpacity;
            SheenWidth = sheenWidth;
        }

        /// <summary>
        /// Milliseconds for one full cycle of the background spectrum
        /// shift.
        /// </summary>
        public double DriftPeriod { get; }

        /// <summary>
        /// Milliseconds for the specular band to travel the rim once.
        /// <para>
        /// DELIBERATELY DIFFERENT from <see cref="DriftPeriod"/>. Two
        /// animations running in lock-step is the mechanical tell: it
        /// reads as a CSS loop rather than as a material, because real
        /// foil responds to TILT and to SPECTRAL DIFFRACTION RATE, which
        /// are not the same clock.
        /// </para>
        /// </summary>
        public double SweepPeriod { get; }

        /// <summary>
        /// The grating axis, degrees. Taken from the shared light rather
        /// than chosen locally — a foil whose sweep points somewhere the
        /// lighting does not reads as a texture pasted over the app.
        /// </summary>
        public double RimAngle { get; }

        public double RimOpacity { get; }

        /// <summary>
        /// The travelling specular band. The brightest thing in this
        /// family and therefore the thing most able to wreck a glyph —
        /// which is why it lives on the RIM and not across the ground.
        /// </summary>
        public double SheenOpacity { get; }

        /// <summary>
        /// Width of that band as a fraction of the rim's diagonal. Wide
        /// bands read as chrome; narrow ones read as foil.
        /// </summary>
        public double SheenWidth { get; }
    }

    /// <summary>The holographic material.</summary>
    public sealed class HoloProfile
    {
        public HoloProfile(
            Color ground, Color groundSecondary, Color groundDetail,
            Color ink, Color mutedInk, Color accent, Color sheen,
            HoloSpectrum spectrum, HoloMotion motion,
            double chromaCeiling, double radius)
        {
            Ground = ground;
            GroundSecondary = groundSecondary;
            GroundDetail = groundDetail;
            Ink = ink;
            MutedInk = mutedInk;
            Accent = accent;
            Sheen = sheen;
            Spectrum = spectrum;
            Motion = motion;
            ChromaCeiling = chromaCeiling;
            Radius = radius;
        }

        /// <summary>
        /// Card radius. Round, unlike Swiss, and unlike neumorphism: the
        /// foil is a thin film ON something, so the something keeps its
        /// own silhouette. Flat at zero would read as a sticker.
        /// </summary>
        public double Radius { get; }

        /// <summary>
        /// The matte ground. OPAQUE, and the only colour text is allowed
        /// to sit on.
        /// </summary>
        public Color Ground { get; }

        public Color GroundSecondary { get; }
        public Color GroundDetail { get; }

        /// <summary>
        /// Body ink. Verified against <see cref="Ground"/> at publish
        /// time, not assumed — see HoloPalette.Build.
        /// </summary>
        public Color Ink { get; }

        public Color MutedInk { get; }

        /// <summary>
        /// The family's real accent, and the ONE place the spectrum is
        /// allowed near a glyph. Even here the ink is measured against
        /// every band rather than trusted.
        /// </summary>
        public Color Accent { get; }

        /// <summary>The specular white, for the travelling band.</summary>
        public Color Sheen { get; }

        public HoloSpectrum Spectrum { get; }

        public HoloMotion Motion { get; }

        /// <summary>
        /// The saturation ceiling the spectrum was built under.
        /// Exposed so a test can assert every band respects it, rather
        /// than inferring it from the colours.
        /// </summary>
        public double ChromaCeiling { get; }
    }

    /// <summary>The resolved construction for one surface in one state.</summary>
    public sealed class HoloStack
    {
        internal HoloStack(
            SoftDepthTier tier,
            SoftInteractionState state,
            Color ground,
            Color ink,
            Color mutedInk,
            IReadOnlyList<Color> rim,
            HoloMotion motion,
            double radius,
            double rimOpacity,
            double accentInkAlpha,
            bool selected,
            bool focused,
            bool reduced)
        {
            Tier = tier;
            State = state;
            Ground = ground;
            Ink = ink;
            MutedInk = mutedInk;
            Rim = rim;
            Motion = motion;
            Radius = radius;
            RimOpacity = rimOpacity;
            AccentInkAlpha = accentInkAlpha;
            Selected = selected;
            Focused = focused;
            MotionReduced = reduced;
        }

        public SoftDepthTier Tier { get; }
        public SoftInteractionState State { get; }

        /// <summary>
        /// The opaque content ground. Text goes HERE, and nowhere else,
        /// for the whole family.
        /// </summary>
        public Color Ground { get; }

        public Color Ink { get; }
        public Color MutedInk { get; }

        /// <summary>
        /// The spectral rim. Decoration. No glyph is ever drawn on this
        /// without <see cref="AccentInkAlpha"/>'s opaque chip behind it.
        /// </summary>
        public IReadOnlyList<Color> Rim { get; }

        public HoloMotion Motion { get; }

        /// <summary>Corner radius for this tier.</summary>
        public double Radius { get; }

        /// <summary>Rim opacity for THIS state, after interaction.</summary>
        public double RimOpacity { get; }

        /// <summary>
        /// Alpha of the opaque chip that backs a glyph sitting on the
        /// foil. 1.0 means the chip is fully opaque and the glyph is
        /// therefore legible on every band; lower would be a lie.
        /// </summary>
        public double AccentInkAlpha { get; }

        public bool Selected { get; }
        public bool Focused { get; }

        /// <summary>
        /// True when the OS asks for reduced motion. The foil then
        /// renders at a FIXED offset rather than animating — not at a
        /// shorter duration. Shortening an animation does not reduce
        /// motion, it just makes the movement harder to predict.
        /// </summary>
        public bool MotionReduced { get; }

        /// <summary>
        /// Always false. The structural promise of this family, in the
        /// same shape as SwissStack.HasShadow: there is no path by
        /// which foil ends up underneath a glyph.
        /// </summary>
        public bool HasFoilUnderText => false;

        /// <summary>
        /// Whether the foil is animated at all. The only permitted
        /// motion in this family.
        /// </summary>
        public bool IsAnimated => !MotionReduced;
    }

    /// <summary>The recipe. Stateless.</summary>
    public sealed class HoloRecipe
    {
        private readonly HoloProfile _holo;
        private readonly bool _dark;
        private readonly bool _reduced;

        public HoloRecipe(HoloProfile holo, bool dark, bool reducedMotion)
        {
            _holo = holo ?? throw new ArgumentNullException(nameof(holo));
            _dark = dark;
            _reduced = reducedMotion;
        }

        /// <summary>
        /// Resolves one surface.
        /// <para>
        /// The two colour sets stay separate all the way through. There
        /// is no branch in this method that puts a spectral colour on
        /// <c>Ground</c>, and that is the whole design: the family fails
        /// its accessibility requirement the moment a label ends up on
        /// a hue it cannot survive.
        /// </para>
        /// </summary>
        public HoloStack Resolve(
            SoftDepthTier tier, SoftInteractionState state, bool selected)
        {
            // The ground is the ramp's surface, and it is OPAQUE in every
            // state. Nothing here ever lifts it toward the spectrum: the
            // foil is on the rim, and the rim is a separate thing.
            Color ground = _holo.Ground;
            Color ink = _holo.Ink;
            Color muted = _holo.MutedInk;

            // Interaction raises the RIM, not the ground. Hovering a
            // holographic surface in most implementations floods the
            // whole panel with colour; here it brings the edge up while
            // the reading surface stays exactly as legible as it was.
            double rimOpacity = _holo.Motion.RimOpacity;
            switch (state)
            {
                case SoftInteractionState.Hover:
                    rimOpacity = Math.Min(1.0, rimOpacity + 0.25);
                    break;
                case SoftInteractionState.Pressed:
                    rimOpacity = Math.Min(1.0, rimOpacity + 0.40);
                    break;
                case SoftInteractionState.Focused:
                    rimOpacity = Math.Min(1.0, rimOpacity + 0.15);
                    break;
                case SoftInteractionState.Disabled:
                    // Disabled FADES THE FOIL rather than fading the
                    // ground. A disabled control that keeps a bright
                    // spectral rim is the brightest thing on the screen,
                    // which is the opposite of what disabled means — and
                    // it is the state where a glowing edge is most
                    // likely to be mistaken for "this one is live".
                    rimOpacity *= 0.35;
                    break;
            }

            // Focus adds a ring OUTSIDE the foil. A ring drawn in a
            // spectral colour is invisible against the neighbouring
            // band of its own gradient, which is the specific reason
            // this one comes from the ramp rather than the spectrum.
            return new HoloStack(
                tier, state, ground, ink, muted,
                Bands(), _holo.Motion,
                RadiusFor(tier),
                rimOpacity,
                accentInkAlpha: 1.0,
                selected,
                focused: state == SoftInteractionState.Focused,
                reduced: _reduced);
        }

        /// <summary>
        /// Corner radius for a tier.
        /// <para>
        /// Larger surfaces get larger radii, following the same 12 / 18 /
        /// 22 / 26 ladder the family profile declares for control /
        /// card / large / hero. A single fixed radius across all four
        /// would make a modal read as a card, which is exactly the
        /// "one radius for everything" tell.
        /// </para>
        /// </summary>
        internal double RadiusFor(SoftDepthTier tier)
        {
            double r = _holo.Radius;
            return tier switch
            {
                SoftDepthTier.Well => r * 0.66,
                SoftDepthTier.Resting => r,
                SoftDepthTier.Raised => r * 0.82,
                SoftDepthTier.Floating => r * 1.22,
                _ => r,
            };
        }

        /// <summary>
        /// The spectrum as flat colours, for a rim brush.
        /// <para>
        /// Returned as plain colours rather than a
        /// <see cref="System.Windows.Media.LinearGradientBrush"/> so the
        /// recipe stays free of any Freezable. That is deliberate: a
        /// brush is a render-time object, and a recipe that handed one
        /// out could not be compared, asserted on or unit-tested without
        /// a dispatcher.
        /// </para>
        /// </summary>
        private IReadOnlyList<Color> Bands()
        {
            var src = _holo.Spectrum.Bands;
            var outp = new Color[src.Count];
            for (int i = 0; i < src.Count; i++) outp[i] = src[i].Color;
            return outp;
        }

        /// <summary>
        /// The WORST contrast between <paramref name="ink"/> and any band
        /// of the spectrum.
        /// <para>
        /// This is the measurement that HoloChip exists to satisfy. A
        /// gradient has no single contrast ratio, so the honest question
        /// is not "what is the contrast on this surface" but "what is
        /// the WORST point on this gradient" — because that is the band
        /// the glyph happens to land on, and it moves while the foil
        /// drifts.
        /// </para>
        /// </summary>
        public double WorstBandContrast(Color ink)
        {
            double worst = double.MaxValue;
            foreach (var band in _holo.Spectrum.Bands)
            {
                double c = HoloPalette.Contrast(ink, band.Color);
                if (c < worst) worst = c;
            }
            return worst;
        }

        /// <summary>
        /// An ink guaranteed legible on EVERY band of the spectrum.
        /// <para>
        /// This is the answer to the research's repeated warning that
        /// "iridescent foils can wreck icon contrast ... use a solid icon
        /// chip so glyphs stay legible on every hue." Because the bands
        /// are solved to a common luminance, the family's own ink
        /// normally already satisfies this and is returned untouched. The
        /// walk toward the ground is the fallback for a caller who
        /// supplies their own ink, and it can only ever improve things.
        /// </para>
        /// </summary>
        public Color ChipInk(Color ink)
        {
            // Fast path, and in practice the only path taken: because
            // the bands are solved to a common luminance, the family's
            // own ink already clears the floor on every one of them.
            if (WorstBandContrast(ink) >= HoloPalette.MinimumBodyContrast)
                return ink;

            return WalkToBandFloor(ink);
        }

        private Color WalkToBandFloor(Color ink)
        {
            // ── NO SINGLE DIRECTION IS CORRECT ──
            //
            // Two plausible rules were tried and both are wrong:
            //
            //   "walk toward the ground" — fails in BOTH modes. Light
            //   mode needs a light ink pushed darker and its ground is
            //   pale; dark mode needs a dark ink pushed lighter and its
            //   ground is nearly black.
            //
            //   "walk AWAY from the bands' luminance" — also wrong.
            //   WCAG's ratio carries a +0.05 in both halves, so moving
            //   a mid-tone DOWN multiplies a small denominator while
            //   moving it UP multiplies a large one, and the downward
            //   step is worth far more. Measured in light mode, #808080
            //   sits at luminance 0.216 against bands at 0.34; walking
            //   "away" toward white reaches 2.67:1, while walking down
            //   reaches 4.66:1. Both moved away. Only one helped.
            //
            // So there is no heuristic here. Both directions are walked,
            // and the candidate that clears the floor with the SMALLEST
            // change is kept — which is also the least surprising result
            // for a caller, since their colour survives whenever it
            // possibly can.
            var best = ink;
            var bestSteps = int.MaxValue;

            for (int step = 1; step <= 20; step++)
            {
                foreach (var toward in ExtremeColors)
                {
                    var trial = HoloPalette.Mix(ink, toward, step / 20.0);
                    if (WorstBandContrast(trial)
                        < HoloPalette.MinimumBodyContrast)
                        continue;

                    if (step < bestSteps)
                    {
                        bestSteps = step;
                        best = trial;
                    }
                }

                // First step at which EITHER direction clears: nothing
                // later can be a smaller change, so stop here.
                if (bestSteps != int.MaxValue) return best;
            }

            // Unreachable given the solved band luminance, which is
            // chosen precisely so that pure black and pure white BOTH
            // clear the floor on every band. Whichever extreme got
            // further is returned, so even an impossible input degrades
            // to the best of two known-good colours rather than to
            // something unchecked.
            double black = WorstBandContrast(Colors.Black);
            return black >= WorstBandContrast(Colors.White)
                ? Colors.Black
                : Colors.White;
        }

        /// <summary>
        /// The two directions a repair can travel. A static array so the
        /// walk allocates nothing — it runs during palette publication,
        /// which is on the UI thread.
        /// </summary>
        private static readonly Color[] ExtremeColors =
        {
            Colors.Black,
            Colors.White,
        };
    }
