// ═══════════════════════════════════════════════════════════════════════
// FILE: Services/Logging/CrashReportService.cs
// PROJECT: ProGlassAutomation
// MODULE: Commercial crash-report sink (offline-first)
//
// PURPOSE
// ───────
// A single, testable service that turns an unhandled
// exception into a structured, shareable crash report
// (text file) and offers the user a way to send it.
//
// This is OFFLINE-FIRST. The default flow is:
//   1. Catch the exception from one of the three .NET
//      exception sinks (UI thread, AppDomain background
//      thread, TaskScheduler unobserved task).
//   2. Write a crash-<timestamp>.txt file in
//      %AppData%\ProGlassAutomation\logs\.
//   3. Also write a copy as crash-latest.txt so support
//      always knows where the newest report is.
//   4. Show a small dialog with the path, a one-click
//      "Open folder" action, a one-click "Send to
//      support" action (opens the user's mail client
//      with the report as an attachment), and a Restart
//      action so the user does not have to manually
//      close and re-open the app.
//   5. The user can OPTIONALLY configure a remote
//      endpoint (see <see cref="RemoteEndpoint"/>) to
//      POST reports automatically. Off by default.
//
// WHAT THE REPORT CONTAINS
// ─────────────────────────
//   * ErrorId (already generated by AppLogService).
//   * UTC + local timestamp.
//   * App version + build label.
//   * OS version + .NET version + 64-bit / 32-bit.
//   * Logged-in user + session id (NOT a password).
//   * License status (edition, customer, expiry).
//   * Current machine fingerprint.
//   * The exception chain (root → inner) with full stack
//     traces, truncated to 8 KB per level.
//   * The last 200 lines from AppLogService's in-memory
//     ring buffer (the most useful diagnostic context
//     for a crash that is the result of a sequence of
//     events, not the exception itself).
//
// WHAT THE REPORT DOES NOT CONTAIN
// ───────────────────────────────
//   * Passwords (we do not store any).
//   * License PRIVATE keys (the app does not have any).
//   * API secrets (the app does not store any in plain
//     text).
//   * Customer / business data. The crash report is a
//     diagnostic, not a data dump.
// ═══════════════════════════════════════════════════════════════════════

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Net.Http;
using System.Text;
using System.Threading;
using System.Threading.Tasks;
using ProGlassAutomation.Services.Audit;
using ProGlassAutomation.Services.Licensing;
using ProGlassAutomation.Services.Updates;

namespace ProGlassAutomation.Services.Logging
{
    /// <summary>
    /// Builds, writes and (optionally) ships crash reports
    /// for the ProGlass Automation app. See the file
    /// header for the offline-first contract.
    /// </summary>
    public static class CrashReportService
    {
        // ── Paths ────────────────────────────────────────────

        /// <summary>
        /// Folder where every crash report is written.
        /// Created on first use.
        /// </summary>
        public static string CrashReportFolder => Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData),
            "ProGlassAutomation", "logs");

        /// <summary>
        /// "Latest" symlink-as-file. Always overwritten with
        /// the most recent report so support can find it
        /// without scanning for timestamps. A real .lic
        /// is the actual report; this name is the shortcut.
        /// </summary>
        public static string CrashReportLatestPath => Path.Combine(
            CrashReportFolder, "crash-latest.txt");

        // ── Remote endpoint (off by default) ──────────────────

        /// <summary>
        /// Optional remote crash endpoint. When set, the
        /// service POSTs the report (as text/plain) to this
        /// URL in addition to writing it locally. Off by
        /// default — the user must opt in. Designed for
        /// the vendor's own internal collector (e.g.
        /// Sentry-compatible intake) so the dev team gets
        /// the report before the user can email it.
        /// </summary>
        public static string? RemoteEndpoint { get; set; }

        /// <summary>
        /// Bearer token used when POSTing to
        /// <see cref="RemoteEndpoint"/>. Null = no auth.
        /// </summary>
        public static string? RemoteEndpointToken { get; set; }

        // ── Report build ─────────────────────────────────────

        /// <summary>
        /// One crash report, in memory. The class is
        /// public so tests can inspect the structure
        /// without re-reading the file.
        /// </summary>
        public sealed class Report
        {
            public string ErrorId { get; init; } = "";
            public DateTime TimestampUtc { get; init; } = DateTime.UtcNow;
            public string AppVersion { get; init; } = "";
            public string BuildLabel { get; init; } = "";
            public string OSVersion { get; init; } = "";
            public string DotNetVersion { get; init; } = "";
            public string Architecture { get; init; } = "";
            public string Username { get; init; } = "";
            public string SessionId { get; init; } = "";
            public string MachineFingerprint { get; init; } = "";
            public string LicenseSummary { get; init; } = "";
            public List<ExceptionEntry> ExceptionChain { get; init; } = new();
            public List<string> RecentLog { get; init; } = new();

            public string ToText()
            {
                var sb = new StringBuilder(8192);
                sb.AppendLine("═══════════════════════════════════════════════════════");
                sb.AppendLine(" ProGlass Automation — crash report");
                sb.AppendLine("═══════════════════════════════════════════════════════");
                sb.AppendLine("Error ID : " + ErrorId);
                sb.AppendLine("Time     : " +
                    TimestampUtc.ToLocalTime().ToString("yyyy-MM-dd HH:mm:ss.fff"));
                sb.AppendLine("Version  : " + AppVersion + " (" + BuildLabel + ")");
                sb.AppendLine("OS       : " + OSVersion);
                sb.AppendLine("Arch     : " + Architecture);
                sb.AppendLine(".NET     : " + DotNetVersion);
                sb.AppendLine("User     : " + Username);
                sb.AppendLine("Session  : " + SessionId);
                sb.AppendLine("Machine  : " + MachineFingerprint);
                sb.AppendLine("License  : " + LicenseSummary);
                sb.AppendLine();
                sb.AppendLine("── Exception chain ──");
                int depth = 0;
                foreach (var e in ExceptionChain)
                {
                    if (depth > 0) sb.AppendLine("── caused by ──");
                    sb.AppendLine("[" + depth + "] " + e.TypeName);
                    sb.AppendLine("    Message : " + e.Message);
                    if (!string.IsNullOrEmpty(e.StackTrace))
                        sb.AppendLine("    Stack   :\n" + e.StackTrace);
                    depth++;
                }

                sb.AppendLine();
                sb.AppendLine("── Last " + RecentLog.Count + " log lines ──");
                foreach (var line in RecentLog) sb.AppendLine(line);

                return sb.ToString();
            }
        }

        /// <summary>
        /// One entry in the exception chain (root → inner).
        /// </summary>
        public sealed class ExceptionEntry
        {
            public string TypeName { get; init; } = "";
            public string Message { get; init; } = "";
            public string StackTrace { get; init; } = "";
        }

        // ── Build from a live exception ──────────────────────

        /// <summary>
        /// Build a <see cref="Report"/> for the supplied
        /// exception. Pulls the recent log buffer, the
        /// license status, the OS, etc. Never throws —
        /// the report is best-effort diagnostic, the
        /// primary error is the exception itself.
        /// </summary>
        public static Report BuildReport(string errorId, Exception root)
        {
            var r = new Report
            {
                ErrorId = string.IsNullOrEmpty(errorId) ? "ERR-UNKNOWN" : errorId,
                TimestampUtc = DateTime.UtcNow,
                AppVersion = SafeGet(() => AppInfo.Version, "unknown"),
                BuildLabel = SafeGet(() => AppInfo.BuildLabel, "unknown"),
                OSVersion = SafeGet(() => Environment.OSVersion.ToString(), "unknown"),
                DotNetVersion = SafeGet(() => Environment.Version.ToString(),
                    "unknown"),
                Architecture =
                    SafeGet(() => IntPtr.Size == 8 ? "x64" : "x86", "unknown"),
                Username = SafeGet(() => AuditService.CurrentUsername, ""),
                SessionId = SafeGet(() => AuditService.SessionId, ""),
                MachineFingerprint =
                    SafeGet(() => MachineFingerprint.ComputeCurrent(), "?"),
                LicenseSummary = SafeGet(BuildLicenseSummary, "?"),
                ExceptionChain = BuildChain(root, maxLevels: 6,
                    stackBudgetPerLevel: 8192),
                RecentLog = SafeGet(() =>
                {
                    var entries = AppLogService.GetRecent(200);
                    return entries.Select(FormatLogLine).ToList();
                }, new List<string>())
            };
            return r;
        }

        private static List<ExceptionEntry> BuildChain(
            Exception? root, int maxLevels, int stackBudgetPerLevel)
        {
            var chain = new List<ExceptionEntry>();
            int depth = 0;
            var current = root;
            while (current != null && depth < maxLevels)
            {
                var stack = current.StackTrace ?? "";
                if (stack.Length > stackBudgetPerLevel)
                {
                    stack = stack.Substring(0, stackBudgetPerLevel) +
                            "\n…(truncated)";
                }
                chain.Add(new ExceptionEntry
                {
                    TypeName = current.GetType().FullName ?? current.GetType().Name,
                    Message = current.Message ?? "",
                    StackTrace = stack
                });
                current = current.InnerException;
                depth++;
            }
            return chain;
        }

        private static string FormatLogLine(LogEntry e)
        {
            var sb = new StringBuilder(256);
            sb.Append(e.TimestampUtc.ToLocalTime()
                .ToString("HH:mm:ss.fff"));
            sb.Append("  [").Append(e.LevelDisplay.PadRight(8)).Append("]");
            if (!string.IsNullOrEmpty(e.ErrorId))
                sb.Append("  (").Append(e.ErrorId).Append(")");
            if (!string.IsNullOrEmpty(e.CorrelationId))
                sb.Append("  ").Append(e.CorrelationId);
            sb.Append("  ").Append(e.Message);
            if (!string.IsNullOrEmpty(e.ExceptionText))
            {
                // One-line exception summary, not the full
                // formatted chain (already in the report).
                var firstLine = e.ExceptionText
                    .Split('\n').FirstOrDefault() ?? "";
                if (firstLine.Length > 200)
                    firstLine = firstLine.Substring(0, 200) + "…";
                sb.Append(" | ").Append(firstLine.Trim());
            }
            return sb.ToString();
        }

        private static string BuildLicenseSummary()
        {
            var s = LicenseService.Current;
            var p = s.Payload;
            if (p == null)
            {
                return s.Status + (string.IsNullOrEmpty(s.ErrorDetail)
                    ? "" : " (" + s.ErrorDetail + ")");
            }
            return string.Format(
                "{0} · {1} · customer={2} · expires={3:u} · {4}",
                s.Status, p.Edition, p.CustomerId, p.ExpiresAt,
                p.MachineFingerprint == null
                    ? "portable"
                    : "bound to " + p.MachineFingerprint);
        }

        // ── Write + (optional) ship ───────────────────────────

        /// <summary>
        /// Write the report to disk: a timestamped file
        /// plus the "crash-latest.txt" shortcut. Returns
        /// the timestamped path. Never throws — a write
        /// failure must not mask the original crash.
        /// </summary>
        public static string WriteReport(Report report)
        {
            try
            {
                Directory.CreateDirectory(CrashReportFolder);
                string stamp = report.TimestampUtc
                    .ToString("yyyyMMdd_HHmmss");
                string fileName = "crash-" + stamp + ".txt";
                string fullPath = Path.Combine(CrashReportFolder, fileName);
                string text = report.ToText();
                File.WriteAllText(fullPath, text, new UTF8Encoding(false));

                // Overwrite crash-latest.txt with the same
                // content. The file is always present so
                // support can find the newest report in one
                // click. We do NOT use a real symlink
                // because Windows requires admin rights.
                try
                {
                    File.Copy(fullPath, CrashReportLatestPath,
                        overwrite: true);
                }
                catch
                {
                    // If the copy fails (e.g. AV holds the
                    // file), the timestamped file is still
                    // there. Move on.
                }

                return fullPath;
            }
            catch
            {
                // Reporting failure must never surface.
                return "";
            }
        }

        /// <summary>
        /// Convenience: build + write + (optionally) POST.
        /// Returns the timestamped file path. Never
        /// throws.
        /// </summary>
        public static string HandleCrash(
            string errorId, Exception root)
        {
            var report = BuildReport(errorId, root);
            string path = WriteReport(report);
            // Fire-and-forget remote shipping. Local
            // success is independent of remote success.
            if (!string.IsNullOrEmpty(RemoteEndpoint) &&
                !string.IsNullOrEmpty(path))
            {
                _ = Task.Run(() => TryPostRemoteAsync(report));
            }
            return path;
        }

        /// <summary>
        /// POST the report to <see cref="RemoteEndpoint"/>.
        /// Best-effort. Never throws. Times out after
        /// 15 seconds so a slow / down server cannot
        /// slow the UI.
        /// </summary>
        public static async Task<bool> TryPostRemoteAsync(Report report)
        {
            if (string.IsNullOrEmpty(RemoteEndpoint)) return false;
            try
            {
                using var http = new HttpClient { Timeout = TimeSpan.FromSeconds(15) };
                if (!string.IsNullOrEmpty(RemoteEndpointToken))
                {
                    http.DefaultRequestHeaders.Authorization =
                        new System.Net.Http.Headers.AuthenticationHeaderValue(
                            "Bearer", RemoteEndpointToken);
                }
                var content = new StringContent(
                    report.ToText(), Encoding.UTF8, "text/plain");
                var resp = await http
                    .PostAsync(RemoteEndpoint, content)
                    .ConfigureAwait(false);
                return resp.IsSuccessStatusCode;
            }
            catch
            {
                // Network error / timeout / TLS failure.
                // We never want a remote failure to bubble.
                return false;
            }
        }

        // ── Helpers ───────────────────────────────────────────

        /// <summary>
        /// Run a delegate and return its result, or
        /// a fallback on any exception. Used so the
        /// crash report builder cannot itself throw.
        /// </summary>
        private static T SafeGet<T>(Func<T> getter, T fallback)
        {
            try { return getter(); } catch { return fallback; }
        }
    }
}
