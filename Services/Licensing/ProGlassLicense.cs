// This is the ONLY surface the app uses to read/verify/validate a
// .proglasslicense file. It:
//   • holds the app's TRUSTED PUBLIC KEYS (never a private key),
//   • delegates all format/signature/validation logic to ProGlass.Licensing,
//   • exposes a stable, structured result (LicenseValidationResult) the UI
//     and services consume — it never parses English error strings.
//
// It is deliberately thin — no duplicated signing/verification logic. The
// public key(s) live here (this is the PUB KEY side of the contract); the
// matching PRIVATE key lives ONLY in the LicenseGenerator.
// ═══════════════════════════════════════════════════════════════════════

using ProGlass.Licensing;

namespace ProGlassAutomation.Services.Licensing;

/// <summary>
/// The app's trusted signing-key ring. A license is accepted when its
/// signature was produced by one of these keyIds. Keep old keys to preserve
/// existing licenses across rotation; add the new key when rotating.
/// </summary>
public static class TrustedLicenseKeys
{
    // ⚠ This is the PUBLIC key (verification). NEVER put a private key here.
    // Generated by ProGlassAutomation.LicenseGenerator.exe → copy the public
    // key (COPY PUBLIC KEY FOR APP) into the placeholder below and rebuild.
    // Until a real public key is embedded, the verifier reports
    // LicenseErrorCode.UnknownKey / a "not configured" state.
    public const string ProductionKeyId = "PLACEHOLDER_KEY_ID";

    public static IReadOnlyDictionary<string, string> All =>
        new Dictionary<string, string>(StringComparer.Ordinal)
        {
            // [ProductionKeyId] = "<RSAKeyValue>...</RSAKeyValue>",
        };
}

/// <summary>
/// Authoritative app-side license verification. Wraps ProGlass.Licensing.
/// </summary>
public static class ProGlassLicense
{
    /// <summary>The product ID the app validates against (permanent).</summary>
    public const string ProductId = ProductIds.ProGlassAutomation;

    /// <summary>Current app version used for version-policy checks.</summary>
    public static string AppVersion =>
        Services.Updates.AppInfo.Version ?? "2.0.0";

    /// <summary>Verify + validate a .proglasslicense file.</summary>
    public static LicenseValidationResult VerifyFile(string path) =>
        LicenseService.VerifyAndValidate(
            LicenseReader.ReadFile(path),
            AppVersion,
            DateTime.UtcNow,
            TrustedLicenseKeys.All,
            currentFingerprint: MachineFingerprint.ComputeCurrent());

    /// <summary>Verify + validate license text (e.g. pasted a key).</summary>
    public static LicenseValidationResult VerifyText(string licenseJson) =>
        LicenseService.VerifyAndValidate(
            LicenseReader.Read(licenseJson),
            AppVersion,
            DateTime.UtcNow,
            TrustedLicenseKeys.All,
            currentFingerprint: MachineFingerprint.ComputeCurrent());

    /// <summary>Does the current license grant a feature (stable ID)?</summary>
    public static bool HasFeature(LicenseDocument? doc, string featureId) =>
        LicenseValidator.HasFeature(doc, featureId);
}
