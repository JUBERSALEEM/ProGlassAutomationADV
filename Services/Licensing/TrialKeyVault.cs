        private static string? _cachedXml;
        private static readonly object _cacheLock = new object();

        /// <summary>
        /// Returns the trial private key XML, reassembled from XOR-masked
        /// shards. Cached after the first call so subsequent verifies
        /// don't repeat the XOR work.
        /// </summary>
        public static string GetPrivateKeyXml()
        {
            var cached = Volatile.Read(ref _cachedXml);
            if (cached != null) return cached;

            lock (_cacheLock)
            {
                if (_cachedXml != null) return _cachedXml;

                int totalLen =
                    _s0Masked.Length + _s1Masked.Length +
                    _s2Masked.Length + _s3Masked.Length;
                byte[] buf = new byte[totalLen];
                int offset = 0;
                CopyAndXor(_s0Masked, _s0Mask, buf, ref offset);
                CopyAndXor(_s1Masked, _s1Mask, buf, ref offset);
                CopyAndXor(_s2Masked, _s2Mask, buf, ref offset);
                CopyAndXor(_s3Masked, _s3Mask, buf, ref offset);

                string xml = Encoding.UTF8.GetString(buf);
                Volatile.Write(ref _cachedXml, xml);
                // Best-effort zero of the intermediate buffer — the
                // string itself sits in the managed heap forever, so
                // this is defence-in-depth against a debugger dump
                // of the interior byte[] specifically.
                Array.Clear(buf, 0, buf.Length);
                return xml;
            }
        }

        /// <summary>
        /// Convenience used by unit tests: forcibly reset the cache
        /// so a swap of the shard arrays (via reflection) takes
        /// effect on the next GetPrivateKeyXml() call. Never used
        /// by production code.
        /// </summary>
        internal static void ResetCacheForTests()
        {
            lock (_cacheLock)
            {
                _cachedXml = null;
            }
        }

        private static void CopyAndXor(
            byte[] masked, byte[] mask, byte[] dest, ref int offset)
        {
            if (masked.Length != mask.Length)
                throw new InvalidOperationException(
                    "TrialKeyVault shard/mask length mismatch — build corrupt.");
            for (int i = 0; i < masked.Length; i++)
                dest[offset + i] = (byte)(masked[i] ^ mask[i]);
            offset += masked.Length;
        }
