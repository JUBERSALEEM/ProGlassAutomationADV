// ═══════════════════════════════════════════════════════════════════════
// FILE: Services/Licensing/LicenseService.cs
// PROJECT: ProGlassAutomation
// MODULE: Commercial licensing — runtime wrapper
//
// PURPOSE
// ───────
// LicenseService is the per-session, per-app state for licensing.
// It owns:
//
//   • The on-disk license file path (default
//     %AppData%\ProGlassAutomation\license.lic).
//   • The latest verification result (re-verified on every
//     Reload() so the app can pick up a freshly-dropped .lic
//     without restarting).
//   • The activation ledger (a small JSON file tracking how many
//     distinct machines have activated this LicenseId so a
//     non-machine-bound license with MaxActivations=3 actually
//     enforces that).
//   • The Trial mode path (which generates a one-shot trial
//     payload, signs it with the developer's private key that
//     lives in %AppData%\ProGlassAutomation\license-keys.json,
//     and stores the resulting .lic in the standard location).
//
//   • The auto-issued 7-day trial on first launch
//     (commit 2 of the licensing refactor): when there is
//     no .lic on disk and no prior trial on this machine,
//     Initialize() generates a 7-day trial signed with the
//     embedded trial private key (LicensePublicKey
//     .TrialPrivateKeyXml), writes it to the standard
//     location, and re-verifies. The trial is marked with
//     TrialSource = "auto-7d" and a separate TrialExpiresAt
//     so the verifier can enforce the 7-day window
//     independently of the canonical ExpiresAt. When the
//     window passes, EnforceTrialExpiry deletes the file and
//     reports TrialExpired; the user must activate a real
//     license to continue.
//
// LICENSE FILE LOCATIONS (searched in order, first hit wins)
//   1. %AppData%\ProGlassAutomation\license.lic
//   2. %AppData%\ProGlassAutomation\license.json  (older format)
//   3. <app folder>\license.lic                       (portable install)
//
// ACTIVATION LEDGER
//   File: %AppData%\ProGlassAutomation\activations.json
//   Schema:
//     {
//       "licenseId": "uuid",
//       "activations": [
//         { "fingerprint": "hex16", "firstSeenUtc": "...", "lastSeenUtc": "..." }
//       ]
//     }
//   On every successful Verify of a non-machine-bound license
//   (MachineFingerprint == null), this machine's fingerprint is
//   added/updated. If the total count exceeds MaxActivations,
//   the verifier returns ActivationLimit.
//
// TRIAL MODE
//   When the user clicks "Start 30-day Trial" in the welcome
//   view, LicenseService generates an in-process
//   LicensePayload(Edition=Trial, ExpiresAt=+30d), signs it
//   with the embedded DEV-ONLY public key (NOT the public key
//   the shipped binary uses), and writes the resulting .lic
//   file. On next Verify, the dev key is consulted; if the
//   license IS a trial, the verifier returns Trial. Trials
//   therefore work without a network or a real issuer.
//
//   The dev key pair is generated by the LicenseGenerator
//   tool the first time it runs and pasted into
//   LicensePublicKey (the public half) AND license-keys.json
//   (the private half). The shipped app does NOT have the
//   private key, so it cannot self-sign — but the developer's
//   machine (where the key pair is generated by the
//   LicenseGenerator) can. Trial mode is therefore a "developer
//   initialised, customer re-issued" flow.
//
// THREAD SAFETY
//   All public members are safe to call from any thread. The
//   internal state is guarded by a single lock; the reload +
//   verify path is the only writer and is short (< 1 ms
//   typically).
// ═══════════════════════════════════════════════════════════════════════

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json;
using System.Text.Json.Serialization;
using ProGlassAutomation.Services.AI.AIConfig;
using ProGlassAutomation.Services.Audit;
using ProGlassAutomation.Services.Database;
using ProGlassAutomation.Services.Logging;

namespace ProGlassAutomation.Services.Licensing
{
    /// <summary>
    /// The runtime license state for the current process. Exposes
    /// the verification result, the activation count, and the
    /// feature allow-list. Raises <see cref="StatusChanged"/>
    /// whenever the state is refreshed.
    /// </summary>
    public static class LicenseService
    {
        // ── File locations ─────────────────────────────────────────

        /// <summary>Default file name for the license.</summary>
        public const string DefaultLicenseFileName = "license.lic";

        /// <summary>File name for the activation ledger.</summary>
        public const string ActivationsFileName = "activations.json";

        // ── State ──────────────────────────────────────────────────

        private static readonly object _lock = new();
        private static LicenseVerificationResult _current =
            new() { Status = LicenseStatus.NotActivated, ErrorDetail = "Not initialized." };

        private static string? _licensePath;
        private static string? _activationsPath;

        /// <summary>
        /// Test-only: when non-null, the service reads /
        /// writes from this folder instead of the real
        /// <c>%AppData%\ProGlassAutomation\</c>. NEVER set
        /// this from production code — it exists so the
        /// LicenseServiceTests can run hermetically without
        /// polluting the developer's machine. The setter is
        /// public-by-necessity (static class) but the
        /// <c>EditorBrowsableState.Never</c> attribute hides
        /// it from IntelliSense so it is not a tempting
        /// target for a real feature.
        /// </summary>
        [System.ComponentModel.EditorBrowsable(
            System.ComponentModel.EditorBrowsableState.Never)]
        public static string? TestDataFolderOverride { get; set; }

        /// <summary>
        /// Fired on every successful Reload so the UI can
        /// rebind the About page and any "license required"
        /// banners.
        /// </summary>
        public static event EventHandler<LicenseVerificationResult>? StatusChanged;

        /// <summary>
        /// The most recent verification result. Always
        /// non-null; before <see cref="Initialize"/> is
        /// called it returns <see cref="LicenseStatus.NotActivated"/>.
        /// </summary>
        public static LicenseVerificationResult Current
        {
            get { lock (_lock) return _current; }
        }

        /// <summary>
        /// True when the app may run with full functionality
        /// (no read-only mode, no missing-features list).
        /// </summary>
        public static bool IsFullyActive
        {
            get
            {
                var s = Current.Status;
                return s == LicenseStatus.Valid
                    || s == LicenseStatus.ExpiringSoon
                    || s == LicenseStatus.Trial;
            }
        }

        /// <summary>
        /// True when the app may run but is not permitted to make new
        /// writes / exports / prints. Two scenarios map here:
        ///   • <see cref="LicenseStatus.GracePeriod"/> — a PAID licence
        ///     has expired but is inside its 7-day grace window.
        ///   • <see cref="LicenseStatus.TrialExpired"/> — the 30-day
        ///     auto-trial has ended; customer data is preserved and the
        ///     wizard remains navigable, but writes are blocked until
        ///     activation. (Behaviour introduced by the August 2026
        ///     licensing refactor — the trial no longer deletes its
        ///     .lic file.)
        /// </summary>
        public static bool IsReadOnlyMode => Current.ReadOnly;

        /// <summary>
        /// Returns the resolved on-disk path of the license
        /// file, or null if no candidate file exists. Used by
        /// the welcome view to populate the "where is the
        /// file" hint.
        /// </summary>
        public static string? ResolvedLicensePath
        {
            get { lock (_lock) return _licensePath; }
        }

        // ── Initialisation ─────────────────────────────────────────

        /// <summary>
        /// Locate the license file (first existing candidate
        /// wins) and verify it. Idempotent — safe to call from
        /// <c>App.OnStartup</c> on every cold start, and again
        /// from the welcome view after a new .lic is dropped.
        ///
        /// First-launch auto-trial (commit 2 of the licensing
        /// refactor): if the verifier returns
        /// <see cref="LicenseStatus.NotActivated"/> AND no trial
        /// has been issued on this machine yet AND the trial
        /// key pair is configured (not the placeholder), this
        /// method auto-issues a 7-day trial, writes it to disk,
        /// and re-verifies. The user gets a working app on
        /// first launch with no manual step.
        /// </summary>
        public static LicenseVerificationResult Initialize()
        {
            lock (_lock)
            {
                string dataRoot = TestDataFolderOverride
                    ?? AppDataRoot.CurrentFolder;
                _activationsPath = Path.Combine(dataRoot, ActivationsFileName);

                // TEST-HOST HYGIENE (cross-check fix, Aug 2026):
                // When the caller has redirected the license folder
                // (TestDataFolderOverride is set), also redirect the
                // TrialLedger's %ProgramData% + registry anchors into
                // the same temp folder — otherwise the LicenseService
                // tests would write "trial issued" markers to the real
                // %ProgramData%\ProGlassAutomation and pollute the
                // developer's actual auto-trial state.
                //
                // Idempotent — if a test explicitly set the ledger
                // override to a different path, we do NOT overwrite it.
                if (TestDataFolderOverride != null)
                {
                    if (TrialLedger.TestProgramDataOverride == null)
                        TrialLedger.TestProgramDataOverride = TestDataFolderOverride;
                    TrialLedger.SkipRegistryAnchorForTests = true;
                }

                _licensePath = ResolveLicensePath(dataRoot);
                _current = LicenseVerifier.Verify(_licensePath ?? string.Empty);

                // ── STRICT INDUSTRIAL LEDGER (Aug 2026 senior audit) ──
                //
                // Beat the ledger heartbeat FIRST — this both detects
                // clock rollback and rewrites LastSeenUtc across all
                // four anchors. A rollback verdict hard-expires any
                // active trial below.
                bool clockRollbackDetected = false;
                try
                {
                    var beat = TrialLedger.Heartbeat();
                    clockRollbackDetected = beat.ClockRollbackDetected;
                }
                catch (System.Exception ex)
                {
                    // A dead ledger must not gate the app — the standard
                    // expiry check on the payload's TrialExpiresAt still
                    // runs below.
                    ProGlassAutomation.Services.Logging.AppLogService.Warning("[LicenseService] Trial ledger unreadable; continuing without heartbeat: " + ex.Message);
                }

                // If the file says we're inside a trial BUT the ledger
                // caught a clock rollback, treat the trial as expired.
                // Same UX as EnforceTrialExpiry — read-only mode, data
                // preserved, banner shows.
                if (clockRollbackDetected
                    && _current.Payload != null
                    && !string.IsNullOrEmpty(_current.Payload.TrialSource))
                {
                    _current = new LicenseVerificationResult
                    {
                        Status = LicenseStatus.TrialExpired,
                        Payload = _current.Payload,
                        ErrorDetail =
                            "System clock rollback detected. The trial is treated as expired. " +
                            "Activate a real licence in Settings → License to continue editing."
                    };
                }

                // Strict trial expiry (unchanged path). See EnforceTrialExpiry
                // for the file-preservation rationale.
                _current = EnforceTrialExpiry(_current, dataRoot);

                // First-launch auto-trial: NotActivated on a fresh
                // machine with no prior trial ⇒ issue a trial. This
                // runs AFTER EnforceTrialExpiry so a TrialExpired
                // state is never accidentally re-issued. The ledger
                // read below is what makes the "one trial per machine"
                // rule strict — deleting %AppData% alone is no longer
                // enough to reset it.
                if (_current.Status == LicenseStatus.NotActivated)
                {
                    _current = IssueAutoTrialIfEligible(dataRoot);
                }

                // For non-machine-bound licenses, count this
                // machine against MaxActivations.
                if (_current.Payload != null
                    && string.IsNullOrEmpty(_current.Payload.MachineFingerprint)
                    && _current.CanRun)
                {
                    _current = EnforceActivationCount(_current);
                }

                try
                {
                    AuditService.Log(
                        AuditSections.Settings,
                        "License checked",
                        $"status={_current.Status}; " +
                        $"customer='{_current.Payload?.CustomerId}'; " +
                        $"company='{_current.Payload?.CompanyName}'; " +
                        $"edition={_current.Payload?.Edition}; " +
                        $"expires={_current.Payload?.ExpiresAt:u}; " +
                        $"file={_licensePath ?? "<none>"}");
                }
                catch { /* audit must not block startup */ }

                return _current;
            }
        }

        /// <summary>
        /// Re-read the license file and re-verify. Use this
        /// after dropping a new .lic into the data folder, or
        /// after <see cref="InstallTrial"/> / <see cref="InstallFile"/>.
        /// </summary>
        public static LicenseVerificationResult Reload()
        {
            LicenseVerificationResult result = Initialize();
            try { StatusChanged?.Invoke(null, result); }
            catch { /* UI subscribers must not break licensing */ }
            return result;
        }

        // ── Path resolution ────────────────────────────────────────

        private static string? ResolveLicensePath(string dataRoot)
        {
            // 1) Default new-format file.
            string primary = Path.Combine(dataRoot, DefaultLicenseFileName);
            if (File.Exists(primary)) return primary;

            // 2) Legacy .json (pre-1.0 builds, never used but
            //    a one-liner fallback costs nothing).
            string legacy = Path.Combine(dataRoot, "license.json");
            if (File.Exists(legacy)) return legacy;

            // 3) Portable install: alongside the executable.
            //    Skipped when the data folder is the test
            //    override — a test must not pick up the
            //    developer's real portable license.
            if (TestDataFolderOverride == null)
            {
                try
                {
                    string exe = System.Diagnostics.Process.GetCurrentProcess()
                        .MainModule?.FileName;
                    if (!string.IsNullOrEmpty(exe))
                    {
                        string portable = Path.Combine(
                            Path.GetDirectoryName(exe) ?? "",
                            DefaultLicenseFileName);
                        if (File.Exists(portable)) return portable;
                    }
                }
                catch { /* portable check is best-effort */ }
            }

            return null;
        }

        // ── Activation ledger ──────────────────────────────────────

        private static LicenseVerificationResult EnforceActivationCount(
            LicenseVerificationResult input)
        {
            var payload = input.Payload!;
            if (string.IsNullOrEmpty(payload.LicenseId))
            {
                // Defensive: an unsigned licenseId is a
                // misconfiguration. The issuer's tool always
                // populates this. We refuse to count activations
                // against a nameless license.
                return new LicenseVerificationResult
                {
                    Status = LicenseStatus.Invalid,
                    Payload = payload,
                    ErrorDetail = "License is missing LicenseId; cannot count activations."
                };
            }

            string fingerprint = MachineFingerprint.ComputeCurrent();
            ActivationLedger ledger = LoadLedger(payload.LicenseId);
            ledger.AlgorithmVersion =
                MachineFingerprint.FingerprintAlgorithmVersion;
            DateTime nowUtc = DateTime.UtcNow;

            // Update this machine's record. If it isn't
            // already in the ledger, add it. We only count
            // the new machine IF we are still under the cap.
            var hit = ledger.Activations
                .FirstOrDefault(a => string.Equals(
                    a.Fingerprint, fingerprint,
                    StringComparison.OrdinalIgnoreCase));

            if (hit == null)
            {
                if (ledger.Activations.Count >= payload.MaxActivations)
                {
                    AuditService.Log(
                        AuditSections.Settings,
                        "License activation limit reached",
                        $"licenseId={payload.LicenseId}; " +
                        $"fingerprint={fingerprint}; " +
                        $"limit={payload.MaxActivations}; " +
                        $"existing={ledger.Activations.Count}");
                    return new LicenseVerificationResult
                    {
                        Status = LicenseStatus.ActivationLimit,
                        Payload = payload,
                        ErrorDetail =
                            "This license has been activated on the maximum " +
                            "number of devices (" + payload.MaxActivations + "). " +
                            "Deactivate another device or contact your vendor."
                    };
                }
                ledger.Activations.Add(new ActivationEntry
                {
                    Fingerprint = fingerprint,
                    FirstSeenUtc = nowUtc,
                    LastSeenUtc = nowUtc
                });
            }
            else
            {
                hit.LastSeenUtc = nowUtc;
            }

            SaveLedger(ledger);

            // Re-emit the original status. The activation
            // check is a pass / fail gate; if it passed we
            // want the same status the verifier returned
            // (Valid / ExpiringSoon / Trial).
            return input;
        }

        private static ActivationLedger LoadLedger(string licenseId)
        {
            try
            {
                if (string.IsNullOrEmpty(_activationsPath) ||
                    !File.Exists(_activationsPath))
                    return new ActivationLedger { LicenseId = licenseId };
                string json = File.ReadAllText(_activationsPath);
                var ledger = JsonSerializer.Deserialize<ActivationLedger>(json,
                    new JsonSerializerOptions
                    {
                        PropertyNameCaseInsensitive = true
                    });
                if (ledger == null)
                    return new ActivationLedger { LicenseId = licenseId };

                // 2026-08-26 (activation-limit incident): the v1
                // fingerprint drifted on every Windows / .NET update,
                // so old ledgers are full of phantom entries from a
                // machine that no longer computes those fingerprints.
                // Counting them would keep the user locked out even
                // though only THIS machine holds the license. Entries
                // recorded under a different algorithm version are
                // therefore discarded: the ledger starts fresh and this
                // machine re-registers on this call.
                if (ledger.AlgorithmVersion !=
                    MachineFingerprint.FingerprintAlgorithmVersion)
                {
                    AppLogService.Info(
                        $"Activation ledger for '{licenseId}' reset: " +
                        $"fingerprint algorithm v{ledger.AlgorithmVersion} " +
                        $"-> v{MachineFingerprint.FingerprintAlgorithmVersion} " +
                        $"({ledger.Activations.Count} stale entr" +
                        $"{(ledger.Activations.Count == 1 ? "y" : "ies")} dropped).",
                        new LogContext
                        {
                            Module = "Licensing",
                            Class = nameof(LicenseService),
                            Operation = "LoadLedger"
                        });
                    return new ActivationLedger { LicenseId = licenseId };
                }
                // If the ledger belongs to a different
                // license, reset it.
                if (!string.Equals(ledger.LicenseId, licenseId,
                        StringComparison.Ordinal))
                {
                    return new ActivationLedger { LicenseId = licenseId };
                }
                return ledger;
            }
            catch (Exception ex)
            {
                AppLogService.Warning(
                    "Could not read activations.json, starting fresh: " + ex.Message,
                    new LogContext
                    {
                        Module = "Licensing",
                        Class = nameof(LicenseService),
                        Operation = "LoadLedger"
                    });
                return new ActivationLedger { LicenseId = licenseId };
            }
        }

        private static void SaveLedger(ActivationLedger ledger)
        {
            if (string.IsNullOrEmpty(_activationsPath)) return;
            try
            {
                Directory.CreateDirectory(Path.GetDirectoryName(_activationsPath)!);
                string json = JsonSerializer.Serialize(ledger,
                    new JsonSerializerOptions { WriteIndented = true });
                File.WriteAllText(_activationsPath, json);
            }
            catch (Exception ex)
            {
                AppLogService.Warning(
                    "Could not write activations.json: " + ex.Message,
                    new LogContext
                    {
                        Module = "Licensing",
                        Class = nameof(LicenseService),
                        Operation = "SaveLedger"
                    });
            }
        }

        // ── Developer self-service (activation-limit recovery) ─────

        /// <summary>
        /// True on machines that hold a local signing key pair
        /// (license-keys.json with PrivateKeyXml) — i.e. the
        /// vendor's / developer's own machine. Same trust basis as
        /// <see cref="InstallTrial"/>, which is the established
        /// developer-only path in this codebase.
        /// </summary>
        public static bool IsDeveloperMachine
        {
            get
            {
                try
                {
                    string dataRoot = TestDataFolderOverride
                        ?? AppDataRoot.CurrentFolder;
                    string keysFile = Path.Combine(dataRoot, "license-keys.json");
                    if (!File.Exists(keysFile)) return false;
                    var keys = JsonSerializer.Deserialize<KeyStore>(
                        File.ReadAllText(keysFile),
                        new JsonSerializerOptions
                        {
                            PropertyNameCaseInsensitive = true
                        });
                    return !string.IsNullOrWhiteSpace(keys?.PrivateKeyXml);
                }
                catch
                {
                    return false;
                }
            }
        }

        /// <summary>
        /// DEVELOPER-ONLY: deletes the activation ledger entirely and
        /// re-verifies. The current machine re-registers itself during
        /// the reload, so a license that was locked out by phantom
        /// ledger entries (fingerprint drift, stale copies) comes back
        /// to life without contacting the vendor.
        /// <para>
        /// Gated on <see cref="IsDeveloperMachine"/>: end-user machines
        /// do not hold the signing key pair, so this path is invisible
        /// and unreachable for them — the activation UI only shows the
        /// button on developer machines.
        /// </para>
        /// </summary>
        public static LicenseVerificationResult DevResetActivations()
        {
            if (!IsDeveloperMachine)
                return _current;

            try
            {
                if (!string.IsNullOrEmpty(_activationsPath)
                    && File.Exists(_activationsPath))
                {
                    File.Delete(_activationsPath);
                }
            }
            catch (Exception ex)
            {
                AppLogService.Warning(
                    "Dev reset: could not delete activations.json: " + ex.Message,
                    new LogContext
                    {
                        Module = "Licensing",
                        Class = nameof(LicenseService),
                        Operation = "DevResetActivations"
                    });
            }

            AppLogService.Info(
                "Activation ledger cleared by developer reset; this " +
                "machine re-registers on reload.",
                new LogContext
                {
                    Module = "Licensing",
                    Class = nameof(LicenseService),
                    Operation = "DevResetActivations"
                });

            try
            {
                AuditService.Log(
                    AuditSections.Settings,
                    "Activation ledger reset (developer)",
                    "activations.json cleared; machine re-registered.");
            }
            catch { /* audit must not block */ }

            return Reload();
        }

        // ── Auto-trial (commit 2 of the licensing refactor) ─────────
        //
        // First-launch behaviour: if the verifier returns
        // NotActivated and no trial has been issued on this
        // machine yet, write an AutoTrialDays-long trial .lic
        // and re-verify. The window is enforced by
        // EnforceTrialExpiry (which returns TrialExpired and
        // drops the app into read-only mode), not by trusting
        // the payload's TrialExpiresAt — a determined user
        // can edit the .lic to extend the window, but the
        // AutoTrialWasIssued flag in AppConfig is the
        // one-per-machine gate so re-issue is refused.

        /// <summary>
        /// How long an auto-issued trial runs. 30 days is the
        /// updated product decision: it matches the industry norm
        /// for evaluation software (Microsoft 365, Adobe, Autodesk
        /// all default to 30 days), gives an operations team a
        /// full month-end billing cycle to try the app in real
        /// production, and leaves plenty of headroom for the
        /// vendor to close the sale before the app is locked out.
        ///
        /// After this window the app switches to read-only mode
        /// (see <see cref="EnforceTrialExpiry"/>) — user data
        /// is preserved, but no new inquiries / invoices / job
        /// orders can be created until a real license is
        /// installed. No customer data is ever destroyed by the
        /// licensing subsystem.
        /// </summary>
        public const int AutoTrialDays = 30;

        /// <summary>
        /// Marker that goes into <see cref="LicensePayload.TrialSource"/>
        /// for an auto-issued trial. The verifier switches
        /// to the trial public key when this marker is
        /// non-empty. The value is a stable disk identifier
        /// (kept as "auto-7d" for backwards compatibility with
        /// pre-existing installs even though the trial is now
        /// <see cref="AutoTrialDays"/> days long); the operator
        /// can grep for this token in the audit log to find
        /// every machine that ever self-issued a trial.
        /// </summary>
        public const string AutoTrialSourceMarker = "auto-7d";

        /// <summary>
        /// Check the loaded license for an expired auto-trial.
        /// If the payload is a trial (TrialSource non-empty)
        /// and the current time is past TrialExpiresAt, return
        /// a new result with <see cref="LicenseStatus.TrialExpired"/>.
        /// The payload — and the .lic file — are preserved so
        /// the UI can still show "your trial expired on
        /// YYYY-MM-DD" and the read-only overlay can offer a
        /// one-click activation path without the user losing
        /// any of their own data.
        ///
        /// PRODUCT DECISION (data preservation):
        /// Earlier versions of this method DELETED the trial
        /// .lic file on expiry to prevent a user from copying
        /// it to another machine. The new licensing contract
        /// makes trial expiry a soft, read-only lock instead:
        /// customer inquiries / invoices / job orders are
        /// never touched by the licensing subsystem. The
        /// AutoTrialWasIssued flag in <see cref="AppConfig"/>
        /// remains the one-per-machine gate (a user who
        /// deletes the .lic themselves does not get a fresh
        /// trial), and CanRun=true / ReadOnly=true is the
        /// runtime enforcement.
        /// </summary>
        private static LicenseVerificationResult EnforceTrialExpiry(
            LicenseVerificationResult input, string dataRoot)
        {
            var p = input.Payload;
            if (p == null) return input;
            if (string.IsNullOrEmpty(p.TrialSource)) return input;
            if (p.TrialExpiresAt == default) return input;

            if (DateTime.UtcNow <= p.TrialExpiresAt.ToUniversalTime())
            {
                return input; // still valid
            }

            // Trial expired. Do NOT delete the .lic file —
            // the read-only lock is enforced by returning
            // TrialExpired below, and preserving the payload
            // means the UI can still render "trial started
            // on X, expired on Y" without a second round-trip.
            // The AutoTrialWasIssued flag prevents re-issue
            // on the next launch.

            try
            {
                if (App.Config != null && !App.Config.AutoTrialWasIssued)
                {
                    App.Config.AutoTrialWasIssued = true;
                    ConfigService.Save(App.Config);
                }
            }
            catch (System.Exception ex)
            {
                // Best effort. If we cannot save the config,
                // the worst case is the next launch re-issues
                // a trial (a second 30-day window) — annoying,
                // not catastrophic, and only happens on a
                // permission-locked profile.
                ProGlassAutomation.Services.Logging.AppLogService.Debug("[LicenseService] Auto-trial config persist failed: " + ex.Message);
            }

            try
            {
                AuditService.Log(
                    AuditSections.Settings,
                    "Auto-trial expired; app entering read-only mode",
                    "licenseId=" + p.LicenseId + "; " +
                    "trialSource=" + p.TrialSource + "; " +
                    "trialExpiresAt=" + p.TrialExpiresAt.ToString("u") + "; " +
                    "dataPreserved=true");
            }
            catch { /* audit must not block startup */ }

            return new LicenseVerificationResult
            {
                Status = LicenseStatus.TrialExpired,
                Payload = p,
                ErrorDetail =
                    "Your " + AutoTrialDays + "-day trial ended on " +
                    p.TrialExpiresAt.ToLocalTime().ToString("yyyy-MM-dd") + ". " +
                    "All your data is preserved. The app is now in " +
                    "read-only mode — activate a full license in " +
                    "Settings → License to continue creating and " +
                    "editing records."
            };
        }

        /// <summary>
        /// If the current state is NotActivated (no license
        /// file on disk) AND no auto-trial has been issued
        /// on this machine yet AND the trial key pair is
        /// configured (not the placeholder), generate a
        /// 7-day trial, sign it with the embedded trial
        /// private key, write it to the default location,
        /// and return the new verification result.
        ///
        /// Gate: <see cref="App.Config"/>'s
        /// <see cref="AppConfig.AutoTrialWasIssued"/> is
        /// false. This is the one-per-machine lock: once a
        /// trial has been issued on a given install, it
        /// never auto-issues again, even if the user
        /// deletes the .lic file.
        /// </summary>
        private static LicenseVerificationResult IssueAutoTrialIfEligible(
            string dataRoot)
        {
            // 1) Trial key pair must be configured. A
            //    developer who has not yet run the
            //    LicenseGenerator to generate a real pair
            //    is left in NotActivated — the same
            //    behaviour as before this commit, so the
            //    audit finding "the public key is the
            //    placeholder" stays loud.
            if (LicensePublicKey.IsTrialKeyPlaceholder)
            {
                return new LicenseVerificationResult
                {
                    Status = LicenseStatus.NotActivated,
                    ErrorDetail =
                        "Trial key pair is the placeholder. The " +
                        "developer must generate a real pair via " +
                        "the LicenseGenerator and paste it into " +
                        "Services/Licensing/LicensePublicKey.cs " +
                        "(TrialPublicKeyXml + TrialPrivateKeyXml) " +
                        "before shipping to a customer."
                };
            }

            // 2) One trial per machine — STRICT, MULTI-ANCHOR.
            //
            //    The old check consulted only App.Config
            //    .AutoTrialWasIssued, which lives in
            //    %AppData%\ProGlassAutomation\config.json. A user
            //    could delete that folder and get another free
            //    trial. The new check consults FOUR independent
            //    anchors (config, %ProgramData% ledger, HKLM
            //    registry, DPAPI blob) via TrialLedger.Read().
            //    If ANY anchor says "issued", refuse.
            //
            //    A determined user with an elevated cmd.exe can
            //    still wipe all four — at that point they own the
            //    machine and can install anything. What this
            //    stops is the casual "reset by deleting AppData"
            //    workflow that industrial ERP users learn from
            //    forums within a week of trial expiry.
            //
            //    Test-environment shortcut kept: null App.Config
            //    means we're in a headless unit test where the
            //    real anchors would pollute the developer's
            //    machine, so we still refuse the auto-trial there.
            if (App.Config == null)
            {
                return new LicenseVerificationResult
                {
                    Status = LicenseStatus.NotActivated,
                    ErrorDetail = "App.Config is not loaded; auto-trial is disabled " +
                                  "(likely a test environment)."
                };
            }

            TrialLedgerSnapshot ledger;
            try { ledger = TrialLedger.Read(); }
            catch { ledger = new TrialLedgerSnapshot { IsIssued = false }; }

            if (App.Config.AutoTrialWasIssued || ledger.IsIssued)
            {
                string evidence = ledger.IsIssued && !string.IsNullOrEmpty(ledger.AnchorEvidence)
                    ? "anchors=" + ledger.AnchorEvidence.TrimEnd(';')
                    : "config-only";

                try
                {
                    AuditService.Log(
                        AuditSections.Settings,
                        "Auto-trial refused — machine already used one",
                        evidence +
                        (ledger.FirstIssuedUtc.HasValue
                            ? "; firstIssued=" + ledger.FirstIssuedUtc.Value.ToString("u")
                            : ""));
                }
                catch { /* audit must not gate the refusal */ }

                return new LicenseVerificationResult
                {
                    Status = LicenseStatus.NotActivated,
                    ErrorDetail =
                        "A trial was previously issued on this machine (" + evidence +
                        "). Only one auto-trial per machine is permitted. " +
                        "Activate a full licence in Settings → License to continue."
                };
            }

            // 3) Build the payload. Same feature set as the
            //    developer-triggered 30-day trial (in
            //    InstallTrial) but duration is 7 days and
            //    TrialSource is the auto marker. ExpiresAt
            //    is set to a far-future date as a safety
            //    net (a customer who flips the clock back
            //    would otherwise bypass the trial), but
            //    TrialExpiresAt is the authoritative value
            //    for an auto-issued trial.
            var now = DateTime.UtcNow;
            var payload = new LicensePayload
            {
                LicenseId = "AUTO-" + Guid.NewGuid().ToString("N"),
                Edition = LicenseEdition.Trial,
                CustomerId = "TRIAL",
                CompanyName = "Trial user",
                IssuedAt = now,
                ExpiresAt = now.AddDays(AutoTrialDays),
                MaxActivations = 1,
                // Auto-trial: every module unlocked out of the box.
                // Product decision — nobody evaluates an industrial
                // suite by clicking on a locked padlock. The 30-day
                // countdown is the constraint, not the feature set.
                // Real Business / Factory / Enterprise licences will
                // narrow this per SKU; the trial is deliberately the
                // full experience.
                Features = new[] { "*" },
                MachineFingerprint = null,    // portable
                Notes = "Auto-issued " + AutoTrialDays + "-day trial (all modules).",
                TrialSource = AutoTrialSourceMarker,
                TrialExpiresAt = now.AddDays(AutoTrialDays)
            };

            // 4) Sign with the embedded trial private key
            //    and write the file. We use the standard
            //    default location so the rest of the
            //    service (ResolveLicensePath, EnforceActivation
            //    Count, audit log) treats it like any other
            //    license.
            string destPath = Path.Combine(dataRoot, DefaultLicenseFileName);
            try
            {
                Directory.CreateDirectory(dataRoot);
                LicenseSigner.SignToFile(
                    payload, LicensePublicKey.TrialPrivateKeyXml, destPath);
            }
            catch (Exception ex)
            {
                return new LicenseVerificationResult
                {
                    Status = LicenseStatus.NotActivated,
                    ErrorDetail =
                        "Could not auto-issue trial: " + ex.Message
                };
            }

            // 5) Persist the one-per-machine flag ACROSS ALL FOUR
            //    ANCHORS via TrialLedger.RecordIssuance. Under the
            //    hood the ledger writes:
            //      • %AppData%\ProGlassAutomation\config.json
            //      • %ProgramData%\ProGlassAutomation\trial-ledger.json
            //      • HKLM\SOFTWARE\ProGlassAutomation\Trial (or HKCU
            //        fallback when the app is running non-elevated)
            //      • DPAPI-encrypted blob in %ProgramData%
            //    Every anchor a user has to wipe raises the bar. The
            //    ledger is best-effort — any single unreachable
            //    anchor is logged but does not fail the ledger write.
            try
            {
                string fp = "";
                try { fp = MachineFingerprint.ComputeCurrent(); } catch { /* silence */ }
                TrialLedger.RecordIssuance(fp);
            }
            catch (Exception ex)
            {
                AppLogService.Warning(
                    "TrialLedger.RecordIssuance threw: " + ex.Message,
                    new LogContext
                    {
                        Module = "Licensing",
                        Class = nameof(LicenseService),
                        Operation = "IssueAutoTrialIfEligible"
                    });
            }

            // Config anchor kept in a second try/catch for
            // symmetry with legacy code that reads
            // AutoTrialWasIssued directly (Duplicate flow, sample
            // data seeding, upgrade migrations). TrialLedger.
            // RecordIssuance already writes this, so the second
            // write is idempotent.
            try
            {
                if (App.Config != null && !App.Config.AutoTrialWasIssued)
                {
                    App.Config.AutoTrialWasIssued = true;
                    ConfigService.Save(App.Config);
                }
            }
            catch (Exception ex)
            {
                AppLogService.Warning(
                    "Could not persist AutoTrialWasIssued flag: " + ex.Message,
                    new LogContext
                    {
                        Module = "Licensing",
                        Class = nameof(LicenseService),
                        Operation = "IssueAutoTrialIfEligible"
                    });
            }

            try
            {
                AuditService.Log(
                    AuditSections.Settings,
                    "Auto-trial issued",
                    "licenseId=" + payload.LicenseId + "; " +
                    "days=" + AutoTrialDays + "; " +
                    "trialSource=" + AutoTrialSourceMarker + "; " +
                    "expires=" + payload.TrialExpiresAt.ToString("u"));
            }
            catch { /* audit must not block startup */ }

            // 6) Re-verify the freshly written file. The
            //    result's Payload is the auto-trial we
            //    just wrote; the status comes back as
            //    Trial (the same branch a customer-issued
            //    trial lands in) so the rest of the
            //    startup can take the standard path.
            return LicenseVerifier.Verify(destPath);
        }

        // ── Trial install ──────────────────────────────────────────

        /// <summary>
        /// Manual trial install — used by the developer
        /// when they need a longer / different-duration
        /// trial than the auto-issued 7-day default. Signs
        /// with the developer's private key from
        /// <c>license-keys.json</c> (the same key the
        /// LicenseGenerator uses) and writes the .lic.
        /// Returns the resulting verification status.
        ///
        /// The trial uses the same key pair as production
        /// licenses — there is no "DEV-ONLY" key. The
        /// constraint on a trial is the <see cref="LicenseEdition.Trial"/>
        /// marker in the payload (the UI shows a trial
        /// banner) and the curated <c>Features[]</c> list
        /// (e.g. "Inquiry.*", "Proforma.*" — but not
        /// "CuttingOptimization.*"). A customer who can run
        /// the LicenseGenerator tool on their own machine
        /// could self-issue a trial of any duration; the
        /// Edition marker is a social contract, not a
        /// cryptographic one. Edition=Business / Factory /
        /// Enterprise requires a real issuer signature,
        /// which requires the private key the customer does
        /// not have.
        ///
        /// Commit 2 of the licensing refactor: this method
        /// is the DEVELOPER-ONLY path. End users on a
        /// shipped install never call this — the 7-day
        /// auto-trial in <see cref="Initialize"/> is the
        /// only trial they get. InstallTrial remains for
        /// the developer's own machine (where the
        /// LicenseGenerator wrote the private key to
        /// license-keys.json).
        /// </summary>
        public static LicenseVerificationResult InstallTrial(int days = 30)
        {
            if (days < 1) days = 1;
            if (days > 365) days = 365;

            var payload = new LicensePayload
            {
                LicenseId = "TRIAL-" + Guid.NewGuid().ToString("N"),
                Edition = LicenseEdition.Trial,
                CustomerId = "TRIAL",
                CompanyName = "Trial user",
                IssuedAt = DateTime.UtcNow,
                ExpiresAt = DateTime.UtcNow.AddDays(days),
                MaxActivations = 1,
                // Developer-issued trial: same "all modules" contract
                // as the auto-trial so QA / demo builds behave like a
                // real evaluation.
                Features = new[] { "*" },
                MachineFingerprint = null,    // portable trial
                Notes = "Trial issued by LicenseService."
            };

            // The trial signer uses the same key pair as
            // production. See the XML doc on this method for
            // why the Edition=Trial marker is the only gate
            // that matters.

            string dataRoot = TestDataFolderOverride
                ?? AppDataRoot.CurrentFolder;
            string destPath = Path.Combine(dataRoot, DefaultLicenseFileName);
            Directory.CreateDirectory(dataRoot);

            // The private key XML is stored next to the
            // public key. The generator writes both halves
            // to license-keys.json on first run. If the file
            // isn't there, refuse — there is no way to sign
            // a trial without the private key.
            string keysFile = Path.Combine(dataRoot, "license-keys.json");
            if (!File.Exists(keysFile))
            {
                return new LicenseVerificationResult
                {
                    Status = LicenseStatus.Invalid,
                    ErrorDetail =
                        "Cannot start a trial because the signing private key " +
                        "is not present at " + keysFile + ". The first-run " +
                        "wizard must run the LicenseGenerator at least once " +
                        "to create this key pair. Contact your vendor."
                };
            }

            string? privateKeyXml;
            try
            {
                var keys = JsonSerializer.Deserialize<KeyStore>(File.ReadAllText(keysFile),
                    new JsonSerializerOptions
                    {
                        PropertyNameCaseInsensitive = true
                    });
                privateKeyXml = keys?.PrivateKeyXml;
            }
            catch (Exception ex)
            {
                return new LicenseVerificationResult
                {
                    Status = LicenseStatus.Invalid,
                    ErrorDetail = "license-keys.json is corrupt: " + ex.Message
                };
            }
            if (string.IsNullOrWhiteSpace(privateKeyXml))
            {
                return new LicenseVerificationResult
                {
                    Status = LicenseStatus.Invalid,
                    ErrorDetail = "license-keys.json has no PrivateKeyXml field."
                };
            }

            try
            {
                LicenseSigner.SignToFile(payload, privateKeyXml, destPath);
            }
            catch (Exception ex)
            {
                return new LicenseVerificationResult
                {
                    Status = LicenseStatus.Invalid,
                    ErrorDetail = "Could not sign trial license: " + ex.Message
                };
            }

            AuditService.Log(
                AuditSections.Settings,
                "Trial license installed",
                "licenseId=" + payload.LicenseId + "; " +
                "days=" + days + "; " +
                "expires=" + payload.ExpiresAt.ToString("u"));

            return Reload();
        }

        /// <summary>
        /// Adopt a license file the user picked from a
        /// file dialog. Copies the file to the default
        /// location (overwriting any existing license) and
        /// re-verifies.
        /// </summary>
        public static LicenseVerificationResult InstallFile(string sourcePath)
        {
            if (string.IsNullOrWhiteSpace(sourcePath) || !File.Exists(sourcePath))
            {
                return new LicenseVerificationResult
                {
                    Status = LicenseStatus.Invalid,
                    ErrorDetail = "Source file does not exist: " + sourcePath
                };
            }

            string dataRoot = TestDataFolderOverride
                ?? AppDataRoot.CurrentFolder;
            string destPath = Path.Combine(dataRoot, DefaultLicenseFileName);
            Directory.CreateDirectory(dataRoot);
            File.Copy(sourcePath, destPath, overwrite: true);

            AuditService.Log(
                AuditSections.Settings,
                "License file installed",
                "source=" + sourcePath + "; dest=" + destPath);

            return Reload();
        }

        // ── Feature gating ─────────────────────────────────────────

        /// <summary>
        /// True when the current license permits the given
        /// feature. A feature string of "Inquiry.*" matches
        /// any feature starting with "Inquiry.". An empty
        /// payload (NotActivated) denies everything.
        /// </summary>
        public static bool FeatureAllowed(string feature)
        {
            var p = Current.Payload;
            if (p == null) return false;
            if (p.Features == null || p.Features.Count == 0) return false;
            foreach (var granted in p.Features)
            {
                if (string.IsNullOrEmpty(granted)) continue;
                if (granted == "*") return true;
                if (granted.EndsWith(".*", StringComparison.Ordinal))
                {
                    string prefix = granted.Substring(0, granted.Length - 1);
                    if (feature.StartsWith(prefix, StringComparison.Ordinal))
                        return true;
                }
                else if (string.Equals(granted, feature, StringComparison.Ordinal))
                {
                    return true;
                }
            }
            return false;
        }

