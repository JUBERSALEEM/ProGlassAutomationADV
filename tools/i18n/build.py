#!/usr/bin/env python3
"""
tools/i18n/build.py — emits Themes/Languages/{Code}.xaml from the short
per-language files next to it (en-US.py, ar-AE.py, … one file per
language). Run:  python tools/i18n/build.py

Rules enforced:
  • en-US.py is canonical — every other language MUST have the same key
    set (missing/extra keys fail the build so a switch never blanks).
  • Output is deterministic; commit the generated .xaml files.
"""
from __future__ import annotations

import html
import importlib.util
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "Themes" / "Languages"

CANONICAL = "en-US"
FILES = sorted(HERE.glob("*.py"))


def load(code: str) -> dict:
    spec = importlib.util.spec_from_file_location(f"i18n_{code}", HERE / f"{code}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)  # noqa: S102 - trusted repo tool
    return dict(mod.STRINGS)


def emit(code: str, table: dict) -> str:
    def enc(v: str) -> str:
        # XAML attribute values cannot contain raw newlines (XML collapses
        # them to spaces), so encode them as &#x0a; AFTER escaping &.
        return html.escape(v, quote=True).replace("\n", "&#x0a;")

    body = "\n".join(
        f'    <sys:String x:Key="{html.escape(k, quote=True)}">'
        f'{enc(v)}</sys:String>'
        for k, v in sorted(table.items()))
    return f"""<!-- ═══════════════════════════════════════════════════════════════
     GENERATED by tools/i18n/build.py from tools/i18n/{code}.py —
     DO NOT EDIT BY HAND.  Language: {code}
═══════════════════════════════════════════════════════════════════ -->
<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
                    xmlns:sys="clr-namespace:System;assembly=System.Runtime">

{body}

</ResourceDictionary>
"""


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    english = load(CANONICAL)
    problems = []
    for f in sorted(FILES):
        code = f.stem
        if code.startswith(("build", "merge", "sweep", "__")):
            continue
        table = load(code)
        missing = [k for k in english if k not in table]
        extra = [k for k in table if k not in english]
        if missing or extra:
            problems.append(f"{code}: missing {len(missing)}, extra {len(extra)}")
            continue
        (OUT / f"{code}.xaml").write_text(emit(code, table), encoding="utf-8")
        print(f"  ✓ {code}.xaml ({len(table)} keys)")
    processed = [f for f in FILES if not f.stem.startswith(("build", "merge", "sweep", "__"))]
    if problems:
        print("INCOMPLETE:", problems)
        return 1
    print(f"Done — {len(processed)} languages.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
