#!/usr/bin/env python3
"""Phase D — generate tools/i18n/msg-keys.py from tools/i18n/msg-spec.json.

msg-keys.py is the single source of truth for the code-behind message keys:
  MSG_KEYS        : {key: english_value}            (217 new keys)
  REUSE_CAPTIONS  : {Msg.CapKey: existingKey}       (17 captions that reuse
                                                     existing dictionary keys)

Also inserts the new keys into tools/i18n/en-US.py (authoritative English)
and writes /tmp/i18n-msgs/{code}-msgs.stub.json translation templates.

Run: python3 tools/i18n/msg-gen.py
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SPEC = json.load(open(HERE / "msg-spec.json", encoding="utf-8"))
KEYS = SPEC["keys"]

REUSE = {
    "Msg.CapAttachments": "DeliveryNote.Attachments",
    "Msg.CapClearAllData": "Settings.ClearDATA",
    "Msg.CapCreateTaxInvoice": "TaxInvoice.CreateTAXInvoice",
    "Msg.CapDeleted": "SheetStore.Deleted",
    "Msg.CapExport": "Action.Export",
    "Msg.CapExportCSV": "DeliveryNote.ExportCSV",
    "Msg.CapExportExcel": "DeliveryNote.ExportExcel",
    "Msg.CapExportPDF": "DeliveryNote.ExportPDF",
    "Msg.CapJobOrders2": "Dashboard.JobOrders",
    "Msg.CapMasterDN": "JobOrder.MasterDN",
    "Msg.CapRemoveSavedKeys": "Settings.RemoveSavedKeys",
    "Msg.CapSampleData": "Settings.SampleDATA",
    "Msg.CapSaved": "ProformaInvoice.Saved",
    "Msg.CapScreenRecording": "Shared.ScreenRecording",
    "Msg.CapUnsavedChanges": "Inquiry.UnsavedChanges",
    "Msg.CapUsers": "SystemCenter.Users",
    "Msg.CapVersionHistory": "Common.VersionHistory",
}

LANGS = ["ar-AE", "zh-CN", "hi-IN", "es-ES", "fr-FR", "de-DE", "ru-RU",
         "pt-BR", "tr-TR", "ur-PK", "bn-BD", "id-ID", "ja-JP", "ko-KR"]


def main():
    new_keys = {k: v for k, v in KEYS.items() if k not in REUSE}

    # 1) msg-keys.py
    out = [
        "# Generated by tools/i18n/msg-gen.py — DO NOT EDIT BY HAND.",
        "# Phase D code-behind message keys. en values must stay byte-identical",
        "# to the previous hard-coded literals (English/AED invariant).",
        "",
        "MSG_KEYS = {",
    ]
    for k in sorted(new_keys):
        out.append(f"    {k!r}: {new_keys[k]['en']!r},")
    out.append("}")
    out.append("")
    out.append("REUSE_CAPTIONS = {")
    for k in sorted(REUSE):
        out.append(f"    {k!r}: {REUSE[k]!r},")
    out.append("}")
    out.append("")
    (HERE / "msg-keys.py").write_text("\n".join(out), encoding="utf-8")
    print(f"msg-keys.py: {len(new_keys)} new keys + {len(REUSE)} reused captions")

    # 2) en-US.py insertion (AST-based, same format as merge-keys.py)
    import ast
    import importlib.util
    en_path = HERE / "en-US.py"
    spec_load = importlib.util.spec_from_file_location("i18n_en_US", en_path)
    mod = importlib.util.module_from_spec(spec_load)
    spec_load.loader.exec_module(mod)  # noqa: S102 - trusted repo tool
    existing = dict(mod.STRINGS)
    # remove stale Msg.* keys from earlier spec runs (authoritative spec wins)
    stale = [k for k in existing if k.startswith("Msg.") and k not in new_keys]
    for k in stale:
        del existing[k]
    added = 0
    fixed = 0
    for k in sorted(new_keys):
        if k not in existing:
            existing[k] = new_keys[k]["en"]
            added += 1
        elif existing[k] != new_keys[k]["en"]:
            existing[k] = new_keys[k]["en"]
            fixed += 1
    body = "".join(
        f"    {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)},\n"
        for k, v in sorted(existing.items()))
    header = en_path.read_text(encoding="utf-8").split("STRINGS = {")[0]
    en_path.write_text(header + "STRINGS = {\n" + body + "}\n", encoding="utf-8")
    print(f"en-US.py: removed {len(stale)} stale, inserted {added}, fixed {fixed} "
          f"(total now {len(existing)})")

    # 3) stub translation templates
    stub_dir = Path("/tmp/i18n-msgs")
    stub_dir.mkdir(exist_ok=True)
    for code in LANGS:
        stub = {k: new_keys[k]["en"] for k in sorted(new_keys)}
        (stub_dir / f"{code}-msgs.stub.json").write_text(
            json.dumps(stub, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"stubs written: {stub_dir}")


if __name__ == "__main__":
    main()
